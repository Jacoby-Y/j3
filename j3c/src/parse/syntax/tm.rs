pub fn tm_grammar() -> String {
    let mut out = String::new();
    out.push_str("{\n");
    field(&mut out, 1, "name", "J3");
    field(&mut out, 1, "scopeName", "source.j3");
    field(
        &mut out,
        1,
        "comment",
        "Generated by j3c dump-syntax from lexer/parser tables. Do not edit.",
    );
    out.push_str("  \"patterns\": [\n");
    includes_block(&mut out, 2, TOP_INCLUDES);
    out.push_str("  ],\n");
    out.push_str("  \"repository\": {\n");
    repo_comments(&mut out);
    sep(&mut out);
    repo_strings(&mut out);
    sep(&mut out);
    repo_interpolate(&mut out);
    sep(&mut out);
    repo_attributes(&mut out);
    sep(&mut out);
    repo_intrinsics(&mut out);
    sep(&mut out);
    repo_module_decl(&mut out);
    sep(&mut out);
    repo_use_lib(&mut out);
    sep(&mut out);
    repo_use_decl(&mut out);
    sep(&mut out);
    repo_fn_decl(&mut out);
    sep(&mut out);
    repo_type_decl(&mut out);
    sep(&mut out);
    repo_const_decl(&mut out);
    sep(&mut out);
    repo_let_decl(&mut out);
    sep(&mut out);
    repo_script_block(&mut out);
    sep(&mut out);
    repo_keywords(&mut out);
    sep(&mut out);
    repo_types(&mut out);
    sep(&mut out);
    repo_constants_bool(&mut out);
    sep(&mut out);
    repo_numbers(&mut out);
    sep(&mut out);
    repo_calls(&mut out);
    sep(&mut out);
    repo_members(&mut out);
    sep(&mut out);
    repo_constants_named(&mut out);
    sep(&mut out);
    repo_variables(&mut out);
    sep(&mut out);
    repo_operators(&mut out);
    sep(&mut out);
    repo_punctuation(&mut out);
    out.push('\n');
    out.push_str("  }\n");
    out.push_str("}\n");
    out
}

pub(super) fn kw(kind: TokenKind) -> &'static str {
    for &(s, k) in KEYWORDS {
        if k == kind {
            return s;
        }
    }
    panic!("keyword kind missing from KEYWORDS: {kind:?}");
}

pub(super) fn sep(out: &mut String) {
    out.push_str(",\n");
}

pub(super) fn field(out: &mut String, indent: usize, key: &str, value: &str) {
    pad(out, indent);
    out.push('"');
    out.push_str(key);
    out.push_str("\": ");
    json_string(out, value);
    out.push_str(",\n");
}

pub(super) fn includes_block(out: &mut String, indent: usize, names: &[&str]) {
    for (i, name) in names.iter().enumerate() {
        pad(out, indent);
        out.push_str("{ \"include\": \"#");
        out.push_str(name);
        out.push_str("\" }");
        if i + 1 != names.len() {
            out.push(',');
        }
        out.push('\n');
    }
}

pub(super) fn include_items(out: &mut String, indent: usize, names: &[&str]) {
    for (i, name) in names.iter().enumerate() {
        pad(out, indent);
        out.push_str("{ \"include\": \"#");
        out.push_str(name);
        out.push_str("\" }");
        if i + 1 != names.len() {
            out.push(',');
        }
        out.push('\n');
    }
}

pub(super) fn pad(out: &mut String, n: usize) {
    for _ in 0..n {
        out.push_str("  ");
    }
}

pub(super) fn json_string(out: &mut String, s: &str) {
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
}

pub(super) fn re_escape(s: &str) -> String {
    let mut o = String::new();
    for c in s.chars() {
        if ".+*?^$()[]{}|\\".contains(c) {
            o.push('\\');
        }
        o.push(c);
    }
    o
}

pub(super) fn word_alts(names: &[&str]) -> String {
    let mut s = String::from("\\b(?:");
    for (i, n) in names.iter().enumerate() {
        if i > 0 {
            s.push('|');
        }
        s.push_str(&re_escape(n));
    }
    s.push_str(")\\b");
    s
}

pub(super) fn match_rule(out: &mut String, indent: usize, name: &str, pat: &str, comma: bool) {
    pad(out, indent);
    out.push_str("{\n");
    pad(out, indent + 1);
    out.push_str("\"name\": ");
    json_string(out, name);
    out.push_str(",\n");
    pad(out, indent + 1);
    out.push_str("\"match\": ");
    json_string(out, pat);
    out.push('\n');
    pad(out, indent);
    out.push('}');
    if comma {
        out.push(',');
    }
    out.push('\n');
}

pub(super) fn match_captures(out: &mut String, indent: usize, pat: &str, caps: &[(&str, &str)], comma: bool) {
    pad(out, indent);
    out.push_str("{\n");
    pad(out, indent + 1);
    out.push_str("\"match\": ");
    json_string(out, pat);
    out.push_str(",\n");
    pad(out, indent + 1);
    out.push_str("\"captures\": {\n");
    for (i, (num, name)) in caps.iter().enumerate() {
        pad(out, indent + 2);
        json_string(out, num);
        out.push_str(": { \"name\": ");
        json_string(out, name);
        out.push_str(" }");
        if i + 1 != caps.len() {
            out.push(',');
        }
        out.push('\n');
    }
    pad(out, indent + 1);
    out.push_str("}\n");
    pad(out, indent);
    out.push('}');
    if comma {
        out.push(',');
    }
    out.push('\n');
}

pub(super) fn op_alts() -> String {
    let mut ops: Vec<&str> = OPERATOR_KINDS
        .iter()
        .filter_map(|k| k.operator_src())
        .collect();
    ops.sort_by(|a, b| b.len().cmp(&a.len()).then(a.cmp(b)));
    let mut pat = String::new();
    for (i, op) in ops.iter().enumerate() {
        if i > 0 {
            pat.push('|');
        }
        pat.push_str(&re_escape(op));
    }
    pat
}
