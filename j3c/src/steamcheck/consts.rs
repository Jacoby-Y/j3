/// The C++ member behind a layout row's field name. Rows use the SDK name without the `m_` prefix;
/// these are the ones that differ or have no prefix (the `Input*Data_t` structs).
pub fn member(strukt: &str, field: &str) -> String {
    const NO_PREFIX: [&str; 3] = ["InputDigitalActionData_t", "InputAnalogActionData_t", "InputMotionData_t"];
    if NO_PREFIX.contains(&strukt) {
        return field.to_string();
    }
    let name = match (strukt, field) {
        ("UserStatsStored_t" | "GlobalAchievementPercentagesReady_t", "gameId") => "nGameID",
        ("SteamInputDeviceConnected_t", "deviceHandle") => "ulConnectedDeviceHandle",
        ("SteamInputDeviceDisconnected_t", "deviceHandle") => "ulDisconnectedDeviceHandle",
        ("SteamInputConfigurationLoaded_t" | "SteamInputGamepadSlotChange_t", "appID") => "unAppID",
        ("SteamInputConfigurationLoaded_t" | "SteamInputGamepadSlotChange_t", "deviceHandle") => "ulDeviceHandle",
        ("SteamInputConfigurationLoaded_t", "mappingCreator") => "ulMappingCreator",
        ("SteamInputConfigurationLoaded_t", "majorRevision") => "unMajorRevision",
        ("SteamInputConfigurationLoaded_t", "minorRevision") => "unMinorRevision",
        ("SteamInputConfigurationLoaded_t", "usesSteamInputAPI") => "bUsesSteamInputAPI",
        ("SteamInputConfigurationLoaded_t", "usesGamepadAPI") => "bUsesGamepadAPI",
        ("SteamInputGamepadSlotChange_t", "deviceType") => "eDeviceType",
        ("SteamInputGamepadSlotChange_t", "oldGamepadSlot") => "nOldGamepadSlot",
        ("SteamInputGamepadSlotChange_t", "newGamepadSlot") => "nNewGamepadSlot",
        ("SteamNetworkingMessage_t", "connUserData") => "nConnUserData",
        ("SteamNetworkingMessage_t", "freeData") => "pfnFreeData",
        ("SteamNetworkingMessage_t", "release") => "pfnRelease",
        ("SteamNetworkingMessage_t", "channel") => "nChannel",
        ("SteamNetworkingMessage_t", "flags") => "nFlags",
        ("SteamNetworkingMessage_t" | "SteamNetConnectionInfo_t", "userData") => "nUserData",
        ("SteamNetConnectionInfo_t", "listenSocket") => "hListenSocket",
        _ => field,
    };
    format!("m_{name}")
}
