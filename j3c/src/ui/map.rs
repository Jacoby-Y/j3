//! Generated J3 text plus the map back to the `.j3ui` it came from.
//!
//! Every byte of generated text sits in one segment. A `copy` segment is J3 lifted verbatim from
//! a `.j3ui` (offsets line up one to one). A `glue` segment is generated code; it maps to the
//! `.j3ui` range of the element or construct that produced it, so an error in glue is shown at
//! that element and never as generated code. The map answers both ways, for the LSP.

#[derive(Debug, Clone)]
pub struct Seg {
    pub lo: usize,
    pub hi: usize,
    pub file: usize,
    pub slo: usize,
    pub shi: usize,
    pub copy: bool,
    /// Extra help line for an error landing in this segment.
    pub hint: Option<&'static str>,
}

/// Where a generated span lands in the sources.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SrcSpan {
    pub file: usize,
    pub lo: usize,
    pub hi: usize,
    pub hint: Option<&'static str>,
}

#[derive(Debug, Default)]
pub struct SpanMap {
    pub segs: Vec<Seg>,
}

impl SpanMap {
    fn find(&self, g: usize) -> Option<&Seg> {
        let k = self.segs.partition_point(|s| s.hi <= g);
        self.segs.get(k).filter(|s| s.lo <= g)
    }

    /// A generated byte range to the source range it stands for.
    pub fn to_src(&self, lo: usize, hi: usize) -> Option<SrcSpan> {
        let a = self.find(lo)?;
        let hi = hi.max(lo + 1);
        if !a.copy {
            return Some(SrcSpan { file: a.file, lo: a.slo, hi: a.shi.max(a.slo + 1), hint: a.hint });
        }
        let start = a.slo + (lo - a.lo);
        let end = if hi <= a.hi {
            a.slo + (hi - a.lo)
        } else {
            match self.find(hi - 1) {
                Some(b) if b.copy && b.file == a.file => b.slo + (hi - b.lo),
                _ => a.shi,
            }
        };
        Some(SrcSpan { file: a.file, lo: start, hi: end.max(start + 1), hint: a.hint })
    }

    /// A source offset to the generated offset of the same byte (copied text only).
    pub fn to_gen(&self, file: usize, pos: usize) -> Option<usize> {
        // A copy that starts at or contains `pos` wins over one that merely ends there: with
        // `!this.canBuy()` the cursor at `canBuy` must not land before the inserted `this.`.
        let hit = |s: &&Seg| s.copy && s.file == file;
        self.segs
            .iter()
            .filter(hit)
            .find(|s| s.slo <= pos && pos < s.shi)
            .or_else(|| self.segs.iter().filter(hit).find(|s| s.slo <= pos && pos <= s.shi))
            .map(|s| s.lo + (pos - s.slo))
    }
}

/// Text under construction. `ctx` is the source range glue is attributed to.
#[derive(Debug, Default)]
pub struct Out {
    pub text: String,
    pub segs: Vec<Seg>,
    pub ctx: (usize, usize, usize),
    pub hint: Option<&'static str>,
    pub ind: usize,
}

impl Out {
    pub fn with_ctx(file: usize) -> Out {
        Out { ctx: (file, 0, 0), ..Out::default() }
    }

    pub fn set(&mut self, file: usize, lo: usize, hi: usize) {
        self.ctx = (file, lo, hi);
    }

    /// Generated code.
    pub fn s(&mut self, t: &str) {
        if t.is_empty() {
            return;
        }
        let lo = self.text.len();
        self.text.push_str(t);
        let (file, slo, shi) = self.ctx;
        if let Some(last) = self.segs.last_mut() {
            if !last.copy && last.hi == lo && last.file == file && last.slo == slo && last.shi == shi && last.hint == self.hint {
                last.hi = self.text.len();
                return;
            }
        }
        self.segs.push(Seg { lo, hi: self.text.len(), file, slo, shi, copy: false, hint: self.hint });
    }

    /// Generated code that stands for the single point `at` in the source.
    pub fn at(&mut self, file: usize, at: usize, t: &str) {
        let saved = self.ctx;
        self.ctx = (file, at, at);
        self.s(t);
        self.ctx = saved;
    }

    /// Indent, then `t`, then a newline.
    pub fn line(&mut self, t: &str) {
        self.pad();
        self.s(t);
        self.s("\n");
    }

    pub fn pad(&mut self) {
        let p = "    ".repeat(self.ind);
        self.s(&p);
    }

    /// J3 copied from the source.
    pub fn copy(&mut self, file: usize, src: &str, lo: usize, hi: usize) {
        if lo >= hi {
            return;
        }
        let g = self.text.len();
        self.text.push_str(&src[lo..hi]);
        self.segs.push(Seg { lo: g, hi: self.text.len(), file, slo: lo, shi: hi, copy: true, hint: self.hint });
    }

    /// Like `copy`, but newlines become spaces (a template hole is one line).
    pub fn copy_flat(&mut self, file: usize, src: &str, lo: usize, hi: usize) {
        let g = self.text.len();
        self.copy(file, src, lo, hi);
        if src[lo..hi].contains('\n') {
            let flat = self.text[g..].replace('\n', " ").replace('\r', "");
            self.text.truncate(g);
            self.text.push_str(&flat);
        }
    }

    pub fn append(&mut self, other: Out) {
        let shift = self.text.len();
        self.text.push_str(&other.text);
        for mut s in other.segs {
            s.lo += shift;
            s.hi += shift;
            self.segs.push(s);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn maps_both_ways() {
        let src = "a.b(c)";
        let mut o = Out::with_ctx(0);
        o.set(0, 0, 6);
        o.s("x = ");
        o.copy(0, src, 0, 6);
        o.s(";");
        let m = SpanMap { segs: o.segs };
        let s = m.to_src(4 + 2, 4 + 3).unwrap();
        assert_eq!((s.lo, s.hi), (2, 3));
        assert_eq!(m.to_gen(0, 2), Some(6));
        let g = m.to_src(0, 2).unwrap();
        assert_eq!((g.lo, g.hi), (0, 6));
    }
}
