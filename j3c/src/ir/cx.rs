//! Interner for types, names, structs, enums, and funcs.

use std::collections::HashMap;

use crate::intern::{Name, Names};
use crate::ir::entity::{EnumDef, Func, GlobalDef, StructDef};
use crate::ir::ids::{EnumId, FieldId, FuncId, GlobalId, StructId};
use crate::ir::ty::{FloatTy, IntTy, Ty, TyKind};
use crate::span::FileId;

/// Builtin types interned once in [`IrCx::new`].
#[derive(Clone, Copy, Debug)]
pub struct CommonTys {
    pub void: Ty,
    pub bool: Ty,
    pub i8: Ty,
    pub i16: Ty,
    pub i32: Ty,
    pub i64: Ty,
    pub u8: Ty,
    pub u16: Ty,
    pub u32: Ty,
    pub u64: Ty,
    pub f32: Ty,
    pub f64: Ty,
    /// Alias of i64. Same interned `Ty` as `i64`.
    pub int: Ty,
    /// Alias of f64. Same interned `Ty` as `f64`.
    pub float: Ty,
    pub ptr: Ty,
    pub cstr: Ty,
    pub string: Ty,
}

pub struct SourceFile {
    pub id: FileId,
    pub path: String,
    pub src: String,
    /// Byte offset where each line starts, so a span's line is a binary search.
    line_starts: Vec<u32>,
    /// Generated code (`.j3ui`): generated byte to the `(path, line)` it came from.
    pub locator: Option<std::sync::Arc<dyn Fn(u32) -> Option<(String, usize)> + Send + Sync>>,
}

impl SourceFile {
    /// 1-based line of byte `pos`; same answer as `parse::line_of`.
    pub fn line(&self, pos: u32) -> usize {
        let pos = pos.min(self.src.len() as u32);
        self.line_starts.partition_point(|&s| s <= pos)
    }

    /// Path and line to report for byte `pos` (the `.j3ui` line for generated code).
    pub fn loc(&self, pos: u32) -> (String, usize) {
        self.locator.as_ref().and_then(|f| f(pos)).unwrap_or_else(|| (self.path.clone(), self.line(pos)))
    }
}

pub struct IrCx {
    names: Names,
    tys: Vec<TyKind>,
    ty_map: HashMap<TyKind, Ty>,
    structs: Vec<StructDef>,
    enums: Vec<EnumDef>,
    funcs: Vec<Func>,
    globals: Vec<GlobalDef>,
    pub common: CommonTys,
    pub files: Vec<SourceFile>,
    file_index: HashMap<FileId, usize>,
}

impl IrCx {
    pub fn new() -> IrCx {
        let mut cx = IrCx {
            names: Names::new(),
            tys: Vec::new(),
            ty_map: HashMap::new(),
            structs: Vec::new(),
            enums: Vec::new(),
            funcs: Vec::new(),
            globals: Vec::new(),
            files: Vec::new(),
            file_index: HashMap::new(),
            common: CommonTys {
                void: Ty(0),
                bool: Ty(0),
                i8: Ty(0),
                i16: Ty(0),
                i32: Ty(0),
                i64: Ty(0),
                u8: Ty(0),
                u16: Ty(0),
                u32: Ty(0),
                u64: Ty(0),
                f32: Ty(0),
                f64: Ty(0),
                int: Ty(0),
                float: Ty(0),
                ptr: Ty(0),
                cstr: Ty(0),
                string: Ty(0),
            },
        };

        let void = cx.intern_ty(TyKind::Void);
        let bool_ty = cx.intern_ty(TyKind::Bool);
        let i8 = cx.intern_ty(TyKind::Int(IntTy::I8));
        let i16 = cx.intern_ty(TyKind::Int(IntTy::I16));
        let i32 = cx.intern_ty(TyKind::Int(IntTy::I32));
        let i64 = cx.intern_ty(TyKind::Int(IntTy::I64));
        let u8 = cx.intern_ty(TyKind::Int(IntTy::U8));
        let u16 = cx.intern_ty(TyKind::Int(IntTy::U16));
        let u32 = cx.intern_ty(TyKind::Int(IntTy::U32));
        let u64 = cx.intern_ty(TyKind::Int(IntTy::U64));
        let f32 = cx.intern_ty(TyKind::Float(FloatTy::F32));
        let f64 = cx.intern_ty(TyKind::Float(FloatTy::F64));
        let ptr = cx.intern_ty(TyKind::Ptr);
        let cstr = cx.intern_ty(TyKind::CStr);
        let string = cx.intern_ty(TyKind::String);

        cx.common = CommonTys {
            void,
            bool: bool_ty,
            i8,
            i16,
            i32,
            i64,
            u8,
            u16,
            u32,
            u64,
            f32,
            f64,
            int: i64,
            float: f64,
            ptr,
            cstr,
            string,
        };

        cx
    }

    pub fn builtin_named(&self, name: &str) -> Option<Ty> {
        match name {
            "void" => Some(self.common.void),
            "bool" => Some(self.common.bool),
            "int" | "i64" => Some(self.common.int),
            "i8" => Some(self.common.i8),
            "i16" => Some(self.common.i16),
            "i32" => Some(self.common.i32),
            "u8" => Some(self.common.u8),
            "u16" => Some(self.common.u16),
            "u32" => Some(self.common.u32),
            "u64" => Some(self.common.u64),
            "f32" => Some(self.common.f32),
            "float" | "f64" => Some(self.common.float),
            "ptr" => Some(self.common.ptr),
            "cstr" => Some(self.common.cstr),
            "string" => Some(self.common.string),
            _ => None,
        }
    }

    pub fn intern_name(&mut self, s: &str) -> Name {
        self.names.intern(s)
    }

    pub fn name_str(&self, name: Name) -> &str {
        self.names.get(name)
    }

    pub fn intern_ty(&mut self, kind: TyKind) -> Ty {
        if let Some(&ty) = self.ty_map.get(&kind) {
            return ty;
        }
        let ty = Ty(self.tys.len() as u32);
        self.tys.push(kind.clone());
        self.ty_map.insert(kind, ty);
        ty
    }

    pub fn lookup_ty(&self, kind: &TyKind) -> Option<Ty> {
        self.ty_map.get(kind).copied()
    }

    pub fn ty_kind(&self, ty: Ty) -> &TyKind {
        &self.tys[ty.0 as usize]
    }

    pub fn ty_ref(&mut self, inner: Ty) -> Ty {
        self.intern_ty(TyKind::Ref(inner))
    }

    pub fn ty_slice(&mut self, elem: Ty) -> Ty {
        self.intern_ty(TyKind::Slice { elem })
    }

    pub fn ty_array(&mut self, elem: Ty, len: u64) -> Ty {
        self.intern_ty(TyKind::Array { elem, len })
    }

    pub fn ty_fn(&mut self, params: Vec<Ty>, ret: Ty) -> Ty {
        self.intern_ty(TyKind::Fn { params, ret })
    }

    pub fn ty_struct(&mut self, id: StructId) -> Ty {
        self.intern_ty(TyKind::Struct(id))
    }

    pub fn ty_enum(&mut self, id: EnumId) -> Ty {
        self.intern_ty(TyKind::Enum(id))
    }

    pub fn alloc_struct(&mut self, def: StructDef) -> StructId {
        let id = StructId(self.structs.len() as u32);
        self.structs.push(def);
        id
    }

    pub fn struct_def(&self, id: StructId) -> &StructDef {
        &self.structs[id.0 as usize]
    }

    pub fn struct_def_mut(&mut self, id: StructId) -> &mut StructDef {
        &mut self.structs[id.0 as usize]
    }

    pub fn field_def(&self, id: FieldId) -> &crate::ir::entity::FieldDef {
        self.struct_def(id.struct_id).field(id)
    }

    pub fn alloc_enum(&mut self, def: EnumDef) -> EnumId {
        let id = EnumId(self.enums.len() as u32);
        self.enums.push(def);
        id
    }

    pub fn enum_def(&self, id: EnumId) -> &EnumDef {
        &self.enums[id.0 as usize]
    }

    pub fn enum_def_mut(&mut self, id: EnumId) -> &mut EnumDef {
        &mut self.enums[id.0 as usize]
    }

    pub fn alloc_func(&mut self, mut func: Func) -> FuncId {
        let id = FuncId(self.funcs.len() as u32);
        func.id = id;
        self.funcs.push(func);
        id
    }

    pub fn func(&self, id: FuncId) -> &Func {
        &self.funcs[id.0 as usize]
    }

    pub fn func_mut(&mut self, id: FuncId) -> &mut Func {
        &mut self.funcs[id.0 as usize]
    }

    pub fn alloc_global(&mut self, mut def: GlobalDef) -> GlobalId {
        let id = GlobalId(self.globals.len() as u32);
        def.id = id;
        self.globals.push(def);
        id
    }

    pub fn global(&self, id: GlobalId) -> &GlobalDef {
        &self.globals[id.0 as usize]
    }

    pub fn funcs(&self) -> &[Func] {
        &self.funcs
    }

    pub fn structs(&self) -> &[StructDef] {
        &self.structs
    }

    pub fn enums(&self) -> &[EnumDef] {
        &self.enums
    }

    pub fn globals(&self) -> &[GlobalDef] {
        &self.globals
    }

    pub fn ref_inner(&self, ty: Ty) -> Option<Ty> {
        match self.ty_kind(ty) {
            TyKind::Ref(inner) => Some(*inner),
            _ => None,
        }
    }

    pub fn elem_ty(&self, ty: Ty) -> Option<Ty> {
        match self.ty_kind(ty) {
            TyKind::Array { elem, .. } => Some(*elem),
            TyKind::Slice { elem } => Some(*elem),
            TyKind::String => Some(self.common.u8),
            _ => None,
        }
    }

    pub fn fn_sig(&self, ty: Ty) -> Option<(&Vec<Ty>, Ty)> {
        match self.ty_kind(ty) {
            TyKind::Fn { params, ret } => Some((params, *ret)),
            _ => None,
        }
    }

    pub fn add_file(&mut self, id: FileId, path: String, src: String) {
        let mut line_starts = vec![0];
        line_starts.extend(src.bytes().enumerate().filter(|(_, b)| *b == b'\n').map(|(i, _)| i as u32 + 1));
        self.file_index.entry(id).or_insert(self.files.len());
        self.files.push(SourceFile { id, path, src, line_starts, locator: None });
    }

    pub fn file(&self, id: FileId) -> Option<&SourceFile> {
        self.file_index.get(&id).map(|&i| &self.files[i])
    }
}

impl Default for IrCx {
    fn default() -> IrCx {
        IrCx::new()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn file_line_matches_line_of() {
        let mut cx = IrCx::new();
        let src = "a\n\nbc\n\n\nlast";
        cx.add_file(FileId(7), "x.j3".to_string(), src.to_string());
        let f = cx.file(FileId(7)).unwrap();
        for p in 0..=src.len() as u32 + 2 {
            assert_eq!(f.line(p), crate::parse::line_of(src, p), "pos {p}");
        }
    }
}
