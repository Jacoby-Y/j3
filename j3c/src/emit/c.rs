//! Print typed modules as C. LLVM later; this is a printer, not the IR.

use std::collections::HashSet;

use crate::emit::c_expr::{self, CWriter};
use crate::emit::c_ty::{self, c_type};
use crate::ir::cx::IrCx;
use crate::ir::entity::{ConstInit, FuncKind};
use crate::ir::ids::StructId;
use crate::ir::module::Module;
use crate::ir::operand::{ConstKind, Operand};
use crate::ir::ty::{Ty, TyKind};

pub fn emit_c(cx: &IrCx, module: &Module) -> Result<String, String> {
    emit_program(cx, std::slice::from_ref(module))
}

pub fn emit_program(cx: &IrCx, modules: &[Module]) -> Result<String, String> {
    let mut out = String::new();
    let syscall = crate::emit::contains_syscall(cx, modules);
    out.push_str("/* generated by j3c — C backend. LLVM later. */\n");
    if syscall {
        out.push_str("/* Host shim: libc syscall on Linux. Pointer args are cast at the call. */\n");
        out.push_str("#define _GNU_SOURCE\n");
    }
    out.push_str("#include <stdint.h>\n");
    out.push_str("#include <limits.h>\n");
    out.push_str("#include <stdbool.h>\n");
    out.push_str("#include <stddef.h>\n");
    out.push_str("#include <stdio.h>\n");
    out.push_str("#include <string.h>\n");
    out.push_str("void _exit(int);\n");
    out.push_str("#define J3_FAIL(m) (fputs(\"runtime check failed: \" m \"\\n\", stderr), _exit(102))\n");
    if syscall {
        out.push_str("#include <unistd.h>\n\n");
        out.push_str("static int64_t j3_syscall(int64_t nr, int64_t a0, int64_t a1, int64_t a2, int64_t a3, int64_t a4, int64_t a5) {\n");
        out.push_str("    return (int64_t)syscall((long)nr, (long)a0, (long)a1, (long)a2, (long)a3, (long)a4, (long)a5);\n");
        out.push_str("}\n\n");
    } else {
        out.push('\n');
    }

    for module in modules {
        for id in &module.structs {
            let cname = c_ty::struct_c_name(cx, *id);
            out.push_str(&format!("typedef struct {cname} {cname};\n"));
        }
    }
    if modules.iter().any(|m| !m.structs.is_empty()) {
        out.push('\n');
    }

    let mut slice_tys = Vec::new();
    collect_slice_tys(cx, modules, &mut slice_tys);
    let mut early_slices = Vec::new();
    let mut fn_slices = Vec::new();
    for ty in slice_tys {
        match cx.elem_ty(ty) {
            Some(elem) if matches!(cx.ty_kind(elem), TyKind::Fn { .. }) => fn_slices.push(ty),
            _ => early_slices.push(ty),
        }
    }
    emit_slice_typedefs(cx, &early_slices, &mut out)?;

    for module in modules {
        for id in &module.enums {
            let def = cx.enum_def(*id);
            if def.is_c_like() {
                continue;
            }
            let cname = c_ty::enum_c_name(cx, *id);
            out.push_str(&format!("typedef struct {cname} {{\n"));
            out.push_str("    int32_t tag;\n");
            out.push_str("    union {\n");
            for (i, v) in def.variants.iter().enumerate() {
                if let Some(pty) = v.payload {
                    let ty = c_type(cx, pty)?;
                    if ty.ends_with('*') {
                        out.push_str(&format!("        {ty}v{i};\n"));
                    } else {
                        out.push_str(&format!("        {ty} v{i};\n"));
                    }
                }
            }
            out.push_str("    } u;\n");
            out.push_str(&format!("}} {cname};\n\n"));
        }
    }

    let mut fn_tys = Vec::new();
    collect_fn_tys(cx, modules, &mut fn_tys);
    for ty in &fn_slices {
        let name = c_ty::slice_name(cx, *ty)?;
        out.push_str(&format!("typedef struct {name} {name};\n"));
    }
    if !fn_slices.is_empty() {
        out.push('\n');
    }
    for ty in &fn_tys {
        out.push_str(&c_ty::fn_typedef(cx, *ty)?);
    }
    if !fn_tys.is_empty() {
        out.push('\n');
    }

    emit_slice_bodies(cx, &fn_slices, &mut out)?;

    emit_struct_bodies(cx, modules, &mut out)?;

    for module in modules {
        for id in &module.globals {
            let g = cx.global(*id);
            let name = c_expr::global_c_name(cx, g);
            let init = match &g.init {
                Some(v) => format!(" = {}", emit_const_init(cx, v)?),
                None => String::new(),
            };
            if let Some((elem, len)) = c_ty::array_parts(cx, g.ty) {
                let elem_c = c_type(cx, elem)?;
                out.push_str(&format!("static {elem_c} {name}[{len}]{init};\n"));
            } else {
                let ty = c_type(cx, g.ty)?;
                if ty.ends_with('*') {
                    out.push_str(&format!("static {ty}{name}{init};\n"));
                } else {
                    out.push_str(&format!("static {ty} {name}{init};\n"));
                }
            }
        }
    }
    if modules.iter().any(|m| !m.globals.is_empty()) {
        out.push('\n');
    }

    let mut w = CWriter::new(cx);

    for module in modules {
        for id in &module.funcs {
            let func = cx.func(*id);
            match &func.kind {
                FuncKind::J3 { .. } | FuncKind::Decl => {
                    out.push_str(&c_expr::proto(cx, func)?);
                    out.push_str(";\n");
                }
                FuncKind::Lib { lib, symbol } => {
                    let (params, ret) = match cx.fn_sig(func.ty) {
                        Some(s) => s,
                        None => return Err("lib func without fn type".to_string()),
                    };
                    let ret_c = c_type(cx, ret)?;
                    let mut args = String::new();
                    for (i, p) in params.iter().enumerate() {
                        if i > 0 {
                            args.push_str(", ");
                        }
                        args.push_str(&c_type(cx, *p)?);
                    }
                    if params.is_empty() {
                        args.push_str("void");
                    }
                    out.push_str(&format!(
                        "/* use lib \"{}\" */\nextern {ret_c} {}({args});\n",
                        cx.name_str(*lib),
                        cx.name_str(*symbol)
                    ));
                }
            }
        }
    }
    out.push('\n');

    for module in modules {
        for id in &module.funcs {
            let func = cx.func(*id);
            let body = match &func.kind {
                FuncKind::J3 { body } => body,
                FuncKind::Decl | FuncKind::Lib { .. } => continue,
            };
            w.body = Some(body);
            out.push_str(&c_expr::proto(cx, func)?);
            out.push_str(" {\n");
            out.push_str(&c_expr::emit_local_decls(&mut w, body)?);
            out.push_str(&w.emit_block(&body.block, false, 1)?);
            out.push_str("}\n\n");
        }
    }

    let entry = host_entry(cx, modules)?;
    let set_args = sys_func(cx, modules, "setArgs");
    out.push_str("int main(int argc, char **argv) {\n");
    if let Some(set_args) = set_args {
        out.push_str(&format!("    {set_args}((int64_t)argc, (void *)argv);\n"));
    } else {
        out.push_str("    (void)argc;\n    (void)argv;\n");
    }
    out.push_str(&format!("    {entry}();\n"));
    out.push_str("    return 0;\n");
    out.push_str("}\n");
    // ponytail: text scan for fmod; flag it in the printer if this grows
    if out.contains("__builtin_fmod") {
        out.push_str("/* use lib \"m\" */\n");
    }

    Ok(out)
}

fn sys_func(cx: &IrCx, modules: &[Module], name: &str) -> Option<String> {
    for module in modules {
        let is_sys = module_is(cx, module, &["j3", "sys"]);
        if !is_sys {
            continue;
        }
        for id in &module.funcs {
            let func = cx.func(*id);
            if cx.name_str(func.name) == name {
                return Some(c_expr::func_c_name(cx, func));
            }
        }
    }
    None
}

fn host_entry(cx: &IrCx, modules: &[Module]) -> Result<String, String> {
    let mut start = None;
    let mut main = None;
    for module in modules {
        let is_sys = module_is(cx, module, &["j3", "sys"]);
        for id in &module.funcs {
            let func = cx.func(*id);
            let name = cx.name_str(func.name);
            if name == "start" && is_sys {
                start = Some(c_expr::func_c_name(cx, func));
            }
            if name == "main" {
                main = Some(c_expr::func_c_name(cx, func));
            }
        }
    }
    match start.or(main) {
        Some(name) => Ok(name),
        None => Err("C emit needs j3.sys.start or fn main()".to_string()),
    }
}

fn module_is(cx: &IrCx, module: &Module, parts: &[&str]) -> bool {
    if module.name.len() != parts.len() {
        return false;
    }
    for (i, part) in parts.iter().enumerate() {
        if cx.name_str(module.name[i]) != *part {
            return false;
        }
    }
    true
}

fn emit_const_init(cx: &IrCx, init: &ConstInit) -> Result<String, String> {
    match init {
        ConstInit::Scalar(op) => match op {
            Operand::Const(c) => match &c.kind {
                ConstKind::F32Bits(bits) => static_f32(*bits),
                ConstKind::F64Bits(bits) => static_f64(*bits),
                _ => {
                    let mut w = CWriter::new(cx);
                    w.operand(op)
                }
            },
            _ => {
                let mut w = CWriter::new(cx);
                w.operand(op)
            }
        },
        ConstInit::Fields(fs) => {
            let mut parts = Vec::new();
            for (name, v) in fs {
                let fname = c_ty::sanitize(name);
                parts.push(format!(".{fname} = {}", emit_const_init(cx, v)?));
            }
            Ok(format!("{{ {} }}", parts.join(", ")))
        }
        ConstInit::Elems(es) => {
            let mut parts = Vec::new();
            for v in es {
                parts.push(emit_const_init(cx, v)?);
            }
            Ok(format!("{{ {} }}", parts.join(", ")))
        }
    }
}

fn static_f32(bits: u32) -> Result<String, String> {
    let value = f32::from_bits(bits);
    if value == 0.0 {
        if bits & 0x8000_0000 != 0 {
            return Ok("-0.0f".to_string());
        }
        return Ok("0.0f".to_string());
    }
    if !value.is_finite() {
        return Err(format!("non-finite f32 in static init: bits={bits}"));
    }
    for prec in [1usize, 8, 9, 12, 17] {
        let mut s = format!("{:.*}", prec, value);
        if s.parse::<f32>().ok().map(|v| v.to_bits()) == Some(bits) {
            if !s.contains('.') && !s.contains('e') && !s.contains('E') {
                s.push_str(".0");
            }
            s.push('f');
            return Ok(s);
        }
    }
    Err(format!("f32 static init did not round-trip: bits={bits}"))
}

fn static_f64(bits: u64) -> Result<String, String> {
    let value = f64::from_bits(bits);
    if value == 0.0 {
        if bits & 0x8000_0000_0000_0000 != 0 {
            return Ok("-0.0".to_string());
        }
        return Ok("0.0".to_string());
    }
    if !value.is_finite() {
        return Err(format!("non-finite f64 in static init: bits={bits}"));
    }
    for prec in [1usize, 8, 9, 12, 17] {
        let mut s = format!("{:.*}", prec, value);
        if s.parse::<f64>().ok().map(|v| v.to_bits()) == Some(bits) {
            if !s.contains('.') && !s.contains('e') && !s.contains('E') {
                s.push_str(".0");
            }
            return Ok(s);
        }
    }
    Err(format!("f64 static init did not round-trip: bits={bits}"))
}

fn emit_struct_bodies(cx: &IrCx, modules: &[Module], out: &mut String) -> Result<(), String> {
    let mut ids = Vec::new();
    for module in modules {
        for id in &module.structs {
            if !ids.contains(id) {
                ids.push(*id);
            }
        }
    }
    let mut ordered = Vec::new();
    let mut seen = HashSet::new();
    for id in ids {
        visit_struct(cx, id, &mut seen, &mut ordered);
    }
    for id in ordered {
        let def = cx.struct_def(id);
        let packed = if def.packed {
            " __attribute__((packed))"
        } else {
            ""
        };
        let cname = c_ty::struct_c_name(cx, id);
        out.push_str(&format!("struct {cname} {{\n"));
        for field in &def.fields {
            let fname = c_ty::sanitize(cx.name_str(field.name));
            if let Some((elem, len)) = c_ty::array_parts(cx, field.ty) {
                let elem_c = c_type(cx, elem)?;
                out.push_str(&format!("    {elem_c} {fname}[{len}];\n"));
                continue;
            }
            let ty = c_type(cx, field.ty)?;
            if ty.ends_with('*') {
                out.push_str(&format!("    {ty}{fname};\n"));
            } else {
                out.push_str(&format!("    {ty} {fname};\n"));
            }
        }
        out.push_str(&format!("}}{packed};\n\n"));
    }
    Ok(())
}

fn visit_struct(
    cx: &IrCx,
    id: StructId,
    seen: &mut HashSet<StructId>,
    ordered: &mut Vec<StructId>,
) {
    if !seen.insert(id) {
        return;
    }
    for field in &cx.struct_def(id).fields {
        for dep in value_structs(cx, field.ty) {
            visit_struct(cx, dep, seen, ordered);
        }
    }
    ordered.push(id);
}

fn value_structs(cx: &IrCx, ty: Ty) -> Vec<StructId> {
    match cx.ty_kind(ty) {
        TyKind::Struct(id) => vec![*id],
        TyKind::Array { elem, .. } => value_structs(cx, *elem),
        _ => Vec::new(),
    }
}

fn emit_slice_fields(
    cx: &IrCx,
    ty: crate::ir::ty::Ty,
    out: &mut String,
) -> Result<(), String> {
    let elem = match cx.elem_ty(ty) {
        Some(e) => e,
        None => return Ok(()),
    };
    let elem_c = c_type(cx, elem)?;
    if elem_c.ends_with('*') {
        out.push_str(&format!("    {elem_c}ptr;\n"));
    } else {
        out.push_str(&format!("    {elem_c} *ptr;\n"));
    }
    out.push_str("    int64_t len;\n");
    Ok(())
}

fn emit_slice_typedefs(
    cx: &IrCx,
    tys: &[crate::ir::ty::Ty],
    out: &mut String,
) -> Result<(), String> {
    for ty in tys {
        let name = c_ty::slice_name(cx, *ty)?;
        out.push_str(&format!("typedef struct {name} {{\n"));
        emit_slice_fields(cx, *ty, out)?;
        out.push_str(&format!("}} {name};\n\n"));
    }
    Ok(())
}

fn emit_slice_bodies(
    cx: &IrCx,
    tys: &[crate::ir::ty::Ty],
    out: &mut String,
) -> Result<(), String> {
    for ty in tys {
        let name = c_ty::slice_name(cx, *ty)?;
        out.push_str(&format!("struct {name} {{\n"));
        emit_slice_fields(cx, *ty, out)?;
        out.push_str("};\n\n");
    }
    Ok(())
}

fn collect_fn_tys(cx: &IrCx, modules: &[Module], out: &mut Vec<crate::ir::ty::Ty>) {
    fn add(out: &mut Vec<crate::ir::ty::Ty>, ty: crate::ir::ty::Ty, cx: &IrCx) {
        match cx.ty_kind(ty) {
            TyKind::Fn { params, ret } => {
                for p in params {
                    add(out, *p, cx);
                }
                add(out, *ret, cx);
                if !out.contains(&ty) {
                    out.push(ty);
                }
            }
            TyKind::Ref(inner) => add(out, *inner, cx),
            TyKind::Slice { elem } => add(out, *elem, cx),
            TyKind::Array { elem, .. } => add(out, *elem, cx),
            _ => {}
        }
    }

    for module in modules {
        for id in &module.structs {
            for field in &cx.struct_def(*id).fields {
                add(out, field.ty, cx);
            }
        }
        for id in &module.funcs {
            let func = cx.func(*id);
            add(out, func.ty, cx);
            if let FuncKind::J3 { body } = &func.kind {
                for decl in &body.locals {
                    add(out, decl.ty, cx);
                }
            }
        }
        for id in &module.globals {
            add(out, cx.global(*id).ty, cx);
        }
    }
}

fn collect_slice_tys(cx: &IrCx, modules: &[Module], out: &mut Vec<crate::ir::ty::Ty>) {
    fn add(out: &mut Vec<crate::ir::ty::Ty>, ty: crate::ir::ty::Ty, cx: &IrCx) {
        match cx.ty_kind(ty) {
            TyKind::Slice { elem } => {
                add(out, *elem, cx);
                if !out.contains(&ty) {
                    out.push(ty);
                }
            }
            TyKind::String => {
                if !out.contains(&ty) {
                    out.push(ty);
                }
            }
            TyKind::Ref(inner) => add(out, *inner, cx),
            TyKind::Array { elem, .. } => add(out, *elem, cx),
            TyKind::Fn { params, ret } => {
                for p in params {
                    add(out, *p, cx);
                }
                add(out, *ret, cx);
            }
            _ => {}
        }
    }

    for module in modules {
        for id in &module.structs {
            for field in &cx.struct_def(*id).fields {
                add(out, field.ty, cx);
            }
        }
        for id in &module.funcs {
            let func = cx.func(*id);
            add(out, func.ty, cx);
            if let FuncKind::J3 { body } = &func.kind {
                for decl in &body.locals {
                    add(out, decl.ty, cx);
                }
            }
        }
        for id in &module.globals {
            add(out, cx.global(*id).ty, cx);
        }
    }
}
