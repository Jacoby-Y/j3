//! Print typed modules as C. LLVM later; this is a printer, not the IR.

use std::collections::HashSet;

use crate::emit::c_expr::{self, CWriter};
use crate::emit::c_static::Statics;
use crate::emit::c_ty::{self, c_type};
use crate::ir::cx::IrCx;
use crate::ir::entity::FuncKind;
use crate::ir::ids::{EnumId, StructId};
use crate::ir::module::Module;
use crate::ir::ty::{Ty, TyKind};

pub fn emit_c(cx: &IrCx, module: &Module) -> Result<String, String> {
    emit_program(cx, std::slice::from_ref(module))
}

pub fn emit_program(cx: &IrCx, modules: &[Module]) -> Result<String, String> {
    let mut out = String::new();
    let syscall = crate::emit::contains_syscall(cx, modules);
    out.push_str("/* generated by j3c — C backend. LLVM later. */\n");
    if syscall {
        out.push_str("/* Host shim: libc syscall on Linux. Pointer args are cast at the call. */\n");
        out.push_str("#define _GNU_SOURCE\n");
    }
    out.push_str("#include <stdint.h>\n");
    out.push_str("#include <limits.h>\n");
    out.push_str("#include <stdbool.h>\n");
    out.push_str("#include <stddef.h>\n");
    out.push_str("#include <stdio.h>\n");
    out.push_str("#include <string.h>\n");
    out.push_str("void _exit(int);\n");
    out.push_str("#define J3_FAIL(m) (fputs(\"runtime check failed: \" m \"\\n\", stderr), _exit(102))\n");
    out.push_str("#define J3_FAILV(m, a, b) (fprintf(stderr, \"runtime check failed: \" m \"\\n\", a, b), _exit(102))\n");
    if syscall {
        out.push_str("#include <unistd.h>\n\n");
        out.push_str("static int64_t j3_syscall(int64_t nr, int64_t a0, int64_t a1, int64_t a2, int64_t a3, int64_t a4, int64_t a5) {\n");
        out.push_str("    return (int64_t)syscall((long)nr, (long)a0, (long)a1, (long)a2, (long)a3, (long)a4, (long)a5);\n");
        out.push_str("}\n\n");
    } else {
        out.push('\n');
    }

    for module in modules {
        for id in &module.structs {
            let cname = c_ty::struct_c_name(cx, *id);
            out.push_str(&format!("typedef struct {cname} {cname};\n"));
        }
        for id in &module.enums {
            if !cx.enum_def(*id).is_c_like() {
                let cname = c_ty::enum_c_name(cx, *id);
                out.push_str(&format!("typedef struct {cname} {cname};\n"));
            }
        }
    }
    if modules.iter().any(|m| !m.structs.is_empty() || !m.enums.is_empty()) {
        out.push('\n');
    }

    let mut slice_tys = Vec::new();
    collect_slice_tys(cx, modules, &mut slice_tys);
    let mut early_slices = Vec::new();
    let mut fn_slices = Vec::new();
    for ty in slice_tys {
        match cx.elem_ty(ty) {
            Some(elem) if matches!(cx.ty_kind(elem), TyKind::Fn { .. }) => fn_slices.push(ty),
            _ => early_slices.push(ty),
        }
    }
    emit_slice_typedefs(cx, &early_slices, &mut out)?;

    let mut fn_tys = Vec::new();
    collect_fn_tys(cx, modules, &mut fn_tys);
    for ty in &fn_slices {
        let name = c_ty::slice_name(cx, *ty)?;
        out.push_str(&format!("typedef struct {name} {name};\n"));
    }
    if !fn_slices.is_empty() {
        out.push('\n');
    }
    // by-value array wrappers, named before the fn types that pass them; bodies with the structs
    let arrays = collect_array_tys(cx, modules, &fn_tys);
    for ty in &arrays {
        let name = c_ty::array_wrap_name(cx, *ty)?;
        out.push_str(&format!("typedef struct {name} {name};\n"));
    }
    for ty in &fn_tys {
        out.push_str(&c_ty::fn_typedef(cx, *ty)?);
    }
    if !fn_tys.is_empty() {
        out.push('\n');
    }

    emit_slice_bodies(cx, &fn_slices, &mut out)?;

    emit_struct_bodies(cx, modules, &arrays, &mut out)?;

    let mut w = CWriter::new(cx);

    for module in modules {
        for id in &module.funcs {
            let func = cx.func(*id);
            match &func.kind {
                FuncKind::J3 { .. } | FuncKind::Decl => {
                    out.push_str(&c_expr::proto(cx, func)?);
                    out.push_str(";\n");
                }
                // stdio.h (included above) declares the real variadic snprintf; a fixed-arity extern would conflict.
                FuncKind::Lib { symbol, .. } if cx.name_str(*symbol) == "snprintf" => {}
                FuncKind::Lib { lib, symbol } => {
                    let (params, ret) = match cx.fn_sig(func.ty) {
                        Some(s) => s,
                        None => return Err("lib func without fn type".to_string()),
                    };
                    let ret_c = c_type(cx, ret)?;
                    let mut args = String::new();
                    for (i, p) in params.iter().enumerate() {
                        if i > 0 {
                            args.push_str(", ");
                        }
                        args.push_str(&c_type(cx, *p)?);
                    }
                    if params.is_empty() {
                        args.push_str("void");
                    }
                    out.push_str(&format!(
                        "/* use lib \"{}\" */\nextern {ret_c} {}({args});\n",
                        cx.name_str(*lib),
                        cx.name_str(*symbol)
                    ));
                }
            }
        }
    }
    out.push('\n');

    // after the prototypes: a method table (`dyn`) holds fn addresses
    let mut data = Statics::default();
    for module in modules {
        for id in &module.globals {
            let g = cx.global(*id);
            let name = c_expr::global_c_name(cx, g);
            let init = match &g.init {
                Some(v) => format!(" = {}", data.init(cx, v)?),
                None => String::new(),
            };
            out.push_str(&std::mem::take(&mut data.arrays));
            let st = if g.thread {
                "static _Thread_local"
            } else {
                "static"
            };
            if c_ty::array_parts(cx, g.ty).is_some() {
                out.push_str(&format!("{st} {}{init};\n", c_ty::array_decl(cx, g.ty, &name)?));
            } else {
                let ty = c_type(cx, g.ty)?;
                if ty.ends_with('*') {
                    out.push_str(&format!("{st} {ty}{name}{init};\n"));
                } else {
                    out.push_str(&format!("{st} {ty} {name}{init};\n"));
                }
            }
        }
    }
    if modules.iter().any(|m| !m.globals.is_empty()) {
        out.push('\n');
    }

    for module in modules {
        for id in &module.funcs {
            let func = cx.func(*id);
            let body = match &func.kind {
                FuncKind::J3 { body } => body,
                FuncKind::Decl | FuncKind::Lib { .. } => continue,
            };
            w.body = Some(body);
            out.push_str(&c_expr::proto(cx, func)?);
            out.push_str(" {\n");
            out.push_str(&c_expr::emit_local_decls(&mut w, body)?);
            out.push_str(&w.emit_block(&body.block, false, 1)?);
            out.push_str("}\n\n");
        }
    }

    let entry = host_entry(cx, modules)?;
    let set_args = sys_func(cx, modules, "setArgs");
    out.push_str("int main(int argc, char **argv) {\n");
    if let Some(set_args) = set_args {
        out.push_str(&format!("    {set_args}((int64_t)argc, (void *)argv);\n"));
    } else {
        out.push_str("    (void)argc;\n    (void)argv;\n");
    }
    out.push_str(&format!("    {entry}();\n"));
    out.push_str("    return 0;\n");
    out.push_str("}\n");
    // vector typedefs and helpers go right after the includes, only when a vector type is named
    if c_expr::uses_vectors(&out) {
        let at = out.find("void _exit(int);\n").unwrap_or(0);
        out.insert_str(at, c_expr::SIMD_PRELUDE);
    }

    if c_expr::uses_half(&out) {
        let at = out.find("void _exit(int);\n").unwrap_or(0);
        out.insert_str(at, c_expr::HALF_PRELUDE);
    }

    // ponytail: text scan for fmod; flag it in the printer if this grows
    if out.contains("__builtin_fmod") || out.contains("__builtin_sqrtf") {
        out.push_str("/* use lib \"m\" */\n");
    }

    Ok(out)
}

fn sys_func(cx: &IrCx, modules: &[Module], name: &str) -> Option<String> {
    for module in modules {
        let is_sys = module_is(cx, module, &["j3", "sys"]);
        if !is_sys {
            continue;
        }
        for id in &module.funcs {
            let func = cx.func(*id);
            if cx.name_str(func.name) == name {
                return Some(c_expr::func_c_name(cx, func));
            }
        }
    }
    None
}

fn host_entry(cx: &IrCx, modules: &[Module]) -> Result<String, String> {
    let mut start = None;
    let mut main = None;
    for module in modules {
        let is_sys = module_is(cx, module, &["j3", "sys"]);
        for id in &module.funcs {
            let func = cx.func(*id);
            let name = cx.name_str(func.name);
            if name == "start" && is_sys {
                start = Some(c_expr::func_c_name(cx, func));
            }
            if name == "main" {
                main = Some(c_expr::func_c_name(cx, func));
            }
        }
    }
    match start.or(main) {
        Some(name) => Ok(name),
        None => Err("C emit needs j3.sys.start or fn main()".to_string()),
    }
}

fn module_is(cx: &IrCx, module: &Module, parts: &[&str]) -> bool {
    if module.name.len() != parts.len() {
        return false;
    }
    for (i, part) in parts.iter().enumerate() {
        if cx.name_str(module.name[i]) != *part {
            return false;
        }
    }
    true
}

/// A by-value type body: a struct or a tagged enum. C needs a body after the bodies it holds.
#[derive(Clone, Copy, PartialEq, Eq, Hash)]
enum Body {
    Struct(StructId),
    Enum(EnumId),
    /// An array's by-value wrapper (`c_ty::array_wrap_name`).
    Array(Ty),
}

fn emit_struct_bodies(cx: &IrCx, modules: &[Module], arrays: &[Ty], out: &mut String) -> Result<(), String> {
    let mut nodes: Vec<Body> = arrays.iter().map(|t| Body::Array(*t)).collect();
    for module in modules {
        for id in &module.structs {
            let n = Body::Struct(*id);
            if !nodes.contains(&n) {
                nodes.push(n);
            }
        }
        for id in &module.enums {
            let n = Body::Enum(*id);
            if !cx.enum_def(*id).is_c_like() && !nodes.contains(&n) {
                nodes.push(n);
            }
        }
    }
    let mut ordered = Vec::new();
    let mut seen = HashSet::new();
    for n in nodes {
        visit_body(cx, n, &mut seen, &mut ordered);
    }
    for n in ordered {
        match n {
            Body::Struct(id) => emit_struct_body(cx, id, out)?,
            Body::Enum(id) => emit_enum_body(cx, id, out)?,
            Body::Array(ty) => {
                let name = c_ty::array_wrap_name(cx, ty)?;
                out.push_str(&format!("struct {name} {{\n    {};\n}};\n\n", c_ty::array_decl(cx, ty, "a")?));
            }
        }
    }
    Ok(())
}

fn emit_struct_body(cx: &IrCx, id: StructId, out: &mut String) -> Result<(), String> {
    let def = cx.struct_def(id);
    let packed = if def.packed {
        " __attribute__((packed))"
    } else {
        ""
    };
    let cname = c_ty::struct_c_name(cx, id);
    out.push_str(&format!("struct {cname} {{\n"));
    for field in &def.fields {
        let fname = c_ty::sanitize(cx.name_str(field.name));
        if c_ty::array_parts(cx, field.ty).is_some() {
            out.push_str(&format!("    {};\n", c_ty::array_decl(cx, field.ty, &fname)?));
            continue;
        }
        let ty = c_type(cx, field.ty)?;
        if ty.ends_with('*') {
            out.push_str(&format!("    {ty}{fname};\n"));
        } else {
            out.push_str(&format!("    {ty} {fname};\n"));
        }
    }
    out.push_str(&format!("}}{packed};\n\n"));
    Ok(())
}

fn emit_enum_body(cx: &IrCx, id: EnumId, out: &mut String) -> Result<(), String> {
    let def = cx.enum_def(id);
    let cname = c_ty::enum_c_name(cx, id);
    out.push_str(&format!("struct {cname} {{\n"));
    out.push_str("    int32_t tag;\n");
    out.push_str("    union {\n");
    for (i, v) in def.variants.iter().enumerate() {
        if let Some(pty) = v.payload {
            let ty = c_type(cx, pty)?;
            if ty.ends_with('*') {
                out.push_str(&format!("        {ty}v{i};\n"));
            } else {
                out.push_str(&format!("        {ty} v{i};\n"));
            }
        }
    }
    out.push_str("    } u;\n");
    out.push_str("};\n\n");
    Ok(())
}

fn visit_body(cx: &IrCx, n: Body, seen: &mut HashSet<Body>, ordered: &mut Vec<Body>) {
    if !seen.insert(n) {
        return;
    }
    let held: Vec<Ty> = match n {
        Body::Struct(id) => cx.struct_def(id).fields.iter().map(|f| f.ty).collect(),
        Body::Enum(id) => cx
            .enum_def(id)
            .variants
            .iter()
            .filter_map(|v| v.payload)
            .collect(),
        Body::Array(ty) => vec![ty],
    };
    for ty in held {
        // an enum holds an array payload in its wrapper
        if matches!(n, Body::Enum(_)) && c_ty::array_parts(cx, ty).is_some() {
            visit_body(cx, Body::Array(ty), seen, ordered);
        }
        for dep in value_bodies(cx, ty) {
            visit_body(cx, dep, seen, ordered);
        }
    }
    ordered.push(n);
}

fn value_bodies(cx: &IrCx, ty: Ty) -> Vec<Body> {
    match cx.ty_kind(ty) {
        TyKind::Struct(id) => vec![Body::Struct(*id)],
        TyKind::Enum(id) if !cx.enum_def(*id).is_c_like() => vec![Body::Enum(*id)],
        TyKind::Array { elem, .. } => value_bodies(cx, *elem),
        _ => Vec::new(),
    }
}

/// Array types C wraps: passed by value (in a fn type, `fn_tys`), an enum payload, or behind a
/// reference (`&[N]T` is a wrapper pointer) in a field, local or global.
fn collect_array_tys(cx: &IrCx, modules: &[Module], fn_tys: &[Ty]) -> Vec<Ty> {
    let mut out = Vec::new();
    let add = |ty: Ty, out: &mut Vec<Ty>| {
        if c_ty::array_parts(cx, ty).is_some() && !out.contains(&ty) {
            out.push(ty);
        }
    };
    // `&[N]T` anywhere inside `ty` (through refs, slices, arrays)
    fn refs(cx: &IrCx, ty: Ty, out: &mut Vec<Ty>, add: &dyn Fn(Ty, &mut Vec<Ty>)) {
        match cx.ty_kind(ty) {
            TyKind::Ref(inner) => {
                add(*inner, out);
                refs(cx, *inner, out, add);
            }
            TyKind::Slice { elem } | TyKind::Array { elem, .. } => refs(cx, *elem, out, add),
            _ => {}
        }
    }
    for ty in fn_tys {
        if let TyKind::Fn { params, ret } = cx.ty_kind(*ty) {
            for t in params.iter().chain(std::iter::once(ret)) {
                add(*t, &mut out);
                refs(cx, *t, &mut out, &add);
            }
        }
    }
    for m in modules {
        for id in &m.enums {
            cx.enum_def(*id).variants.iter().filter_map(|v| v.payload).for_each(|t| add(t, &mut out));
        }
        let fields = m.structs.iter().flat_map(|id| cx.struct_def(*id).fields.iter().map(|f| f.ty));
        let locals = m.funcs.iter().flat_map(|id| match &cx.func(*id).kind {
            FuncKind::J3 { body } => body.locals.iter().map(|d| d.ty).collect(),
            _ => Vec::new(),
        });
        let globals = m.globals.iter().map(|id| cx.global(*id).ty);
        for t in fields.chain(locals).chain(globals).collect::<Vec<_>>() {
            refs(cx, t, &mut out, &add);
        }
    }
    out
}

fn emit_slice_fields(
    cx: &IrCx,
    ty: crate::ir::ty::Ty,
    out: &mut String,
) -> Result<(), String> {
    let elem = match cx.elem_ty(ty) {
        Some(e) => e,
        None => return Ok(()),
    };
    let elem_c = c_type(cx, elem)?;
    if elem_c.ends_with('*') {
        out.push_str(&format!("    {elem_c}ptr;\n"));
    } else {
        out.push_str(&format!("    {elem_c} *ptr;\n"));
    }
    out.push_str("    int64_t len;\n");
    Ok(())
}

fn emit_slice_typedefs(
    cx: &IrCx,
    tys: &[crate::ir::ty::Ty],
    out: &mut String,
) -> Result<(), String> {
    for ty in tys {
        let name = c_ty::slice_name(cx, *ty)?;
        out.push_str(&format!("typedef struct {name} {{\n"));
        emit_slice_fields(cx, *ty, out)?;
        out.push_str(&format!("}} {name};\n\n"));
    }
    Ok(())
}

fn emit_slice_bodies(
    cx: &IrCx,
    tys: &[crate::ir::ty::Ty],
    out: &mut String,
) -> Result<(), String> {
    for ty in tys {
        let name = c_ty::slice_name(cx, *ty)?;
        out.push_str(&format!("struct {name} {{\n"));
        emit_slice_fields(cx, *ty, out)?;
        out.push_str("};\n\n");
    }
    Ok(())
}

fn collect_fn_tys(cx: &IrCx, modules: &[Module], out: &mut Vec<crate::ir::ty::Ty>) {
    fn add(out: &mut Vec<crate::ir::ty::Ty>, ty: crate::ir::ty::Ty, cx: &IrCx) {
        match cx.ty_kind(ty) {
            TyKind::Fn { params, ret } => {
                for p in params {
                    add(out, *p, cx);
                }
                add(out, *ret, cx);
                if !out.contains(&ty) {
                    out.push(ty);
                }
            }
            TyKind::Ref(inner) => add(out, *inner, cx),
            TyKind::Slice { elem } => add(out, *elem, cx),
            TyKind::Array { elem, .. } => add(out, *elem, cx),
            _ => {}
        }
    }

    for module in modules {
        for id in &module.structs {
            for field in &cx.struct_def(*id).fields {
                add(out, field.ty, cx);
            }
        }
        for id in &module.funcs {
            let func = cx.func(*id);
            add(out, func.ty, cx);
            if let FuncKind::J3 { body } = &func.kind {
                for decl in &body.locals {
                    add(out, decl.ty, cx);
                }
            }
        }
        for id in &module.globals {
            add(out, cx.global(*id).ty, cx);
        }
    }
}

fn collect_slice_tys(cx: &IrCx, modules: &[Module], out: &mut Vec<crate::ir::ty::Ty>) {
    fn add(out: &mut Vec<crate::ir::ty::Ty>, ty: crate::ir::ty::Ty, cx: &IrCx) {
        match cx.ty_kind(ty) {
            TyKind::Slice { elem } => {
                add(out, *elem, cx);
                if !out.contains(&ty) {
                    out.push(ty);
                }
            }
            TyKind::String => {
                if !out.contains(&ty) {
                    out.push(ty);
                }
            }
            TyKind::Ref(inner) => add(out, *inner, cx),
            TyKind::Array { elem, .. } => add(out, *elem, cx),
            TyKind::Fn { params, ret } => {
                for p in params {
                    add(out, *p, cx);
                }
                add(out, *ret, cx);
            }
            _ => {}
        }
    }

    for module in modules {
        for id in &module.structs {
            for field in &cx.struct_def(*id).fields {
                add(out, field.ty, cx);
            }
        }
        for id in &module.funcs {
            let func = cx.func(*id);
            add(out, func.ty, cx);
            if let FuncKind::J3 { body } = &func.kind {
                for decl in &body.locals {
                    add(out, decl.ty, cx);
                }
            }
        }
        for id in &module.globals {
            add(out, cx.global(*id).ty, cx);
        }
    }
}
