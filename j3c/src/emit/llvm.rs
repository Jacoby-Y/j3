/// Which functions one LLVM text defines. A split build compiles the script VM at `-O2`
/// as its own object while the rest of a dev build stays at the project's `opt`.
#[derive(Clone, Copy)]
pub enum Part<'a> {
    Whole,
    /// Define only these; declare everything else, and reference globals as external.
    Only(&'a HashSet<FuncId>),
    /// Define everything except these, plus `main` and every global.
    Except(&'a HashSet<FuncId>),
}

impl Part<'_> {
    fn defines(&self, id: FuncId) -> bool {
        match self {
            Part::Whole => true,
            Part::Only(set) => set.contains(&id),
            Part::Except(set) => !set.contains(&id),
        }
    }

    fn split(&self) -> bool {
        !matches!(self, Part::Whole)
    }
}

pub fn emit_llvm(cx: &IrCx, modules: &[Module], opts: &EmitOpts) -> Result<String, String> {
    emit_llvm_part(cx, modules, opts, Part::Whole)
}

pub fn emit_llvm_part(
    cx: &IrCx,
    modules: &[Module],
    opts: &EmitOpts,
    part: Part,
) -> Result<String, String> {
    let triple = if opts.target.is_empty() {
        "x86_64-pc-linux-gnu"
    } else {
        opts.target.as_str()
    };
    let mut out = String::new();
    out.push_str("; generated by j3c — LLVM printer\n");
    out.push_str(&format!("target triple = \"{triple}\"\n"));
    out.push_str("target datalayout = \"e-m:e-p270:32:32-p271:32:32-p272:64:64-i64:64-i128:128-f80:128-n8:16:32:64-S128\"\n\n");
    out.push_str("%j3_string = type { ptr, i64 }\n\n");

    emit_struct_types(cx, modules, &mut out)?;
    emit_enum_types(cx, modules, &mut out)?;

    if crate::emit::contains_syscall(cx, modules) {
        out.push_str("declare i64 @syscall(i64, ...)\n");
    }
    out.push_str("declare void @_exit(i32) noreturn\n");
    out.push_str("declare i64 @write(i32, ptr, i64)\n");
    out.push_str("declare void @llvm.memcpy.p0.p0.i64(ptr noalias nocapture writeonly, ptr noalias nocapture readonly, i64, i1 immarg)\n");
    out.push_str("declare i32 @snprintf(ptr noundef, i64 noundef, ptr noundef, ...)\n");
    out.push_str("declare i32 @puts(ptr)\n\n");

    out.push_str("@.j3_fmt_i64 = private unnamed_addr constant [5 x i8] c\"%lld\\00\"\n");
    out.push_str("@.j3_fmt_f = private unnamed_addr constant [3 x i8] c\"%g\\00\"\n");
    out.push_str("@.j3_fmt_s = private unnamed_addr constant [3 x i8] c\"%s\\00\"\n");
    out.push_str("@.j3_true = private unnamed_addr constant [5 x i8] c\"true\\00\"\n");
    out.push_str("@.j3_false = private unnamed_addr constant [6 x i8] c\"false\\00\"\n\n");

    // Several modules may bind the same C function (`getenv` in two `use lib "c"` blocks);
    // LLVM takes one declaration per symbol.
    let mut declared = std::collections::HashSet::new();
    for module in modules {
        for id in &module.funcs {
            let func = cx.func(*id);
            if let FuncKind::Lib { lib, symbol } = &func.kind {
                if !declared.insert(*symbol) { continue; }
                out.push_str(&format!("; use lib \"{}\"\n", cx.name_str(*lib)));
                out.push_str(&format!(
                    "declare {} @{}({})\n",
                    ll_ret(cx, func.ty)?,
                    c_ty::sanitize(cx.name_str(*symbol)),
                    ll_params(cx, func.ty)?
                ));
            }
        }
    }
    out.push('\n');

    for module in modules {
        for id in &module.globals {
            let g = cx.global(*id);
            let name = c_expr::global_c_name(cx, g);
            let ty = ll_type(cx, g.ty)?;
            if matches!(part, Part::Only(_)) {
                out.push_str(&format!(
                    "@{name} = external {}global {ty}, align {}\n",
                    tls(g),
                    llvm_ty::align(cx, g.ty)
                ));
                continue;
            }
            let mut pre = String::new();
            let init = match &g.init {
                Some(v) => ll_const_init(cx, g.ty, v, &name, &mut pre)?,
                None => "zeroinitializer".to_string(),
            };
            out.push_str(&pre);
            let linkage = if part.split() { "" } else { "internal " };
            out.push_str(&format!(
                "@{name} = {linkage}{}global {ty} {init}, align {}\n",
                tls(g),
                llvm_ty::align(cx, g.ty)
            ));
        }
    }
    if modules.iter().any(|m| !m.globals.is_empty()) {
        out.push('\n');
    }

    crate::phase::detail("types, globals, debug scopes");
    let t_dbg = std::time::Instant::now();
    let mut dbg = if opts.cc.debug && !matches!(part, Part::Only(_)) {
        DebugOut::prepare(cx, modules, None)
    } else {
        DebugOut::off()
    };
    if matches!(part, Part::Whole) {
        crate::cli::timing("  emit: types, globals, debug scopes", t_dbg);
    }
    let t_funcs = std::time::Instant::now();
    if dbg.enabled() {
        out.push_str("declare void @llvm.dbg.declare(metadata, metadata, metadata)\n\n");
    }
    // Whole programs print every failed check through one routine; split and per-module
    // builds keep a message per site (they exist for fast dev builds, not for size).
    let pack = matches!(part, Part::Whole);
    let mut abort_files: Vec<String> = Vec::new();
    for (n, module) in modules.iter().enumerate() {
        if matches!(part, Part::Whole) {
            let name: Vec<&str> = module.name.iter().map(|p| cx.name_str(*p)).collect();
            crate::phase::detail(&format!("functions {}/{} {}", n + 1, modules.len(), name.join(".")));
        }
        for id in &module.funcs {
            let func = cx.func(*id);
            match &func.kind {
                FuncKind::J3 { .. } if !part.defines(*id) => {
                    out.push_str(&format!(
                        "declare {} @{}({})\n",
                        ll_ret(cx, func.ty)?,
                        c_expr::func_c_name(cx, func),
                        ll_params(cx, func.ty)?
                    ));
                }
                FuncKind::J3 { body } => {
                    let slot = if dbg.enabled() {
                        Some(&mut dbg)
                    } else {
                        None
                    };
                    let mut f = LlvmFn::new(cx, body, slot);
                    f.external = part.split();
                    f.nounwind = super::host::release_nounwind(opts.cc.release, triple);
                    if pack {
                        f.abort_files = Some(&mut abort_files);
                    }
                    out.push_str(&f.emit_func(func)?);
                    out.push('\n');
                }
                FuncKind::Decl | FuncKind::Lib { .. } => {}
            }
        }
    }
    if pack && !abort_files.is_empty() {
        out.push_str(&abort_routine(&abort_files));
    }
    if matches!(part, Part::Whole) {
        crate::cli::timing("  emit: function bodies", t_funcs);
    }

    if !matches!(part, Part::Only(_)) {
        let entry = host_entry(cx, modules)?;
        let crash = opts.cc.debug && super::llvm_crash::supported(triple);
        if crash {
            out.push_str(&super::llvm_crash::definitions());
        }
        out.push_str("define i32 @main(i32 %argc, ptr %argv) {\n");
        if crash {
            out.push_str(&super::llvm_crash::install());
        }
        if let Some(set_args) = sys_func(cx, modules, "setArgs") {
            out.push_str("  %argc64 = sext i32 %argc to i64\n");
            out.push_str(&format!("  call void @{set_args}(i64 %argc64, ptr %argv)\n"));
        }
        out.push_str(&format!("  call void @{entry}()\n"));
        out.push_str("  ret i32 0\n");
        out.push_str("}\n");
    }
    crate::phase::detail("finishing debug metadata");
    let t_meta = std::time::Instant::now();
    let meta = dbg.finish();
    if matches!(part, Part::Whole) {
        crate::cli::timing("  emit: debug metadata", t_meta);
    }
    if !meta.is_empty() {
        out.push('\n');
        out.push_str(super::llvm_crash::ATTRS);
        out.push_str(&meta);
    }
    // `frem` lowers to a libm call.
    // ponytail: text scan for frem; flag it in the printer if this grows
    if out.contains(" frem ") {
        out.push_str("; use lib \"m\"\n");
    }
    Ok(out)
}

/// `@j3_abort(i64 file << 40 | line << 8 | kind)`: prints `file:line: message\n` to stderr and
/// exits 102, the same text a per-site message gave. One copy replaces a string and a call
/// sequence at every bounds, divide, and format check.
fn abort_routine(files: &[String]) -> String {
    use crate::ir::stmt::AbortKind;
    let mut out = String::from("\n");
    let table = |name: &str, texts: Vec<String>, out: &mut String| {
        let mut items = Vec::new();
        for (i, s) in texts.iter().enumerate() {
            let mut body = String::new();
            for b in s.bytes() {
                if b.is_ascii_graphic() && b != b'"' && b != b'\\' || b == b' ' {
                    body.push(b as char);
                } else {
                    body.push_str(&format!("\\{b:02X}"));
                }
            }
            out.push_str(&format!(
                "@{name}.s{i} = private unnamed_addr constant [{} x i8] c\"{body}\"\n",
                s.len()
            ));
            items.push(format!("%j3_string {{ ptr @{name}.s{i}, i64 {} }}", s.len()));
        }
        out.push_str(&format!(
            "@{name} = private unnamed_addr constant [{} x %j3_string] [{}]\n",
            texts.len(),
            items.join(", ")
        ));
    };
    table("j3_abort_files", files.iter().map(|f| format!("{f}:")).collect(), &mut out);
    table(
        "j3_abort_kinds",
        AbortKind::ALL.iter().map(|k| format!(": {}\n", k.message())).collect(),
        &mut out,
    );
    out.push_str(
        "define internal void @j3_abort(i64 %v) noinline cold noreturn nounwind {
entry:
  %buf = alloca [12 x i8], align 1
  %kind = and i64 %v, 255
  %line = lshr i64 %v, 8
  %line32 = and i64 %line, 4294967295
  %file = lshr i64 %v, 40
  %fp = getelementptr %j3_string, ptr @j3_abort_files, i64 %file, i32 0
  %fl = getelementptr %j3_string, ptr @j3_abort_files, i64 %file, i32 1
  %fptr = load ptr, ptr %fp
  %flen = load i64, ptr %fl
  %w0 = call i64 @write(i32 2, ptr %fptr, i64 %flen)
  br label %digits
digits:
  %n = phi i64 [ %line32, %entry ], [ %q, %digits ]
  %pos = phi i64 [ 12, %entry ], [ %p1, %digits ]
  %p1 = sub i64 %pos, 1
  %r = urem i64 %n, 10
  %q = udiv i64 %n, 10
  %c = add i64 %r, 48
  %c8 = trunc i64 %c to i8
  %dp = getelementptr i8, ptr %buf, i64 %p1
  store i8 %c8, ptr %dp
  %more = icmp ne i64 %q, 0
  br i1 %more, label %digits, label %done
done:
  %len = sub i64 12, %p1
  %w1 = call i64 @write(i32 2, ptr %dp, i64 %len)
  %kp = getelementptr %j3_string, ptr @j3_abort_kinds, i64 %kind, i32 0
  %kl = getelementptr %j3_string, ptr @j3_abort_kinds, i64 %kind, i32 1
  %kptr = load ptr, ptr %kp
  %klen = load i64, ptr %kl
  %w2 = call i64 @write(i32 2, ptr %kptr, i64 %klen)
  call void @_exit(i32 102)
  unreachable
}
",
    );
    out
}

/// One module's LLVM text. Types are duplicated. This module's functions and
/// globals are defined (external linkage); everything else is declared. `@main`
/// is only in the module that owns `j3.sys.start` or user `main`.
///
/// `chunk` is (index, functions): a module with giant functions is split over several objects,
/// and each defines only its share (see `chunk_assign`). Chunk 0 also owns the globals and `@main`.
pub(crate) fn emit_llvm_module(
    cx: &IrCx,
    modules: &[Module],
    index: usize,
    opts: &EmitOpts,
    chunk: Option<(usize, &HashSet<FuncId>)>,
) -> Result<String, String> {
    let mine = &modules[index];
    let all: HashSet<FuncId>;
    let (chunk_no, defined) = match chunk {
        Some((n, set)) => (n, set),
        None => {
            all = mine.funcs.iter().copied().collect();
            (0, &all)
        }
    };
    let triple = if opts.target.is_empty() {
        "x86_64-pc-linux-gnu"
    } else {
        opts.target.as_str()
    };
    let mut out = String::new();
    out.push_str("; generated by j3c — LLVM printer\n");
    out.push_str(&format!("target triple = \"{triple}\"\n"));
    out.push_str("target datalayout = \"e-m:e-p270:32:32-p271:32:32-p272:64:64-i64:64-i128:128-f80:128-n8:16:32:64-S128\"\n\n");
    out.push_str("%j3_string = type { ptr, i64 }\n\n");

    emit_struct_types(cx, modules, &mut out)?;
    emit_enum_types(cx, modules, &mut out)?;

    if crate::emit::contains_syscall(cx, modules) {
        out.push_str("declare i64 @syscall(i64, ...)\n");
    }
    out.push_str("declare void @_exit(i32) noreturn\n");
    out.push_str("declare i64 @write(i32, ptr, i64)\n");
    out.push_str("declare void @llvm.memcpy.p0.p0.i64(ptr noalias nocapture writeonly, ptr noalias nocapture readonly, i64, i1 immarg)\n");
    out.push_str("declare i32 @snprintf(ptr noundef, i64 noundef, ptr noundef, ...)\n");
    out.push_str("declare i32 @puts(ptr)\n\n");

    out.push_str("@.j3_fmt_i64 = private unnamed_addr constant [5 x i8] c\"%lld\\00\"\n");
    out.push_str("@.j3_fmt_f = private unnamed_addr constant [3 x i8] c\"%g\\00\"\n");
    out.push_str("@.j3_fmt_s = private unnamed_addr constant [3 x i8] c\"%s\\00\"\n");
    out.push_str("@.j3_true = private unnamed_addr constant [5 x i8] c\"true\\00\"\n");
    out.push_str("@.j3_false = private unnamed_addr constant [6 x i8] c\"false\\00\"\n\n");

    let mut declared = HashSet::new();
    for module in modules {
        for id in &module.funcs {
            let func = cx.func(*id);
            if let FuncKind::Lib { lib, symbol } = &func.kind {
                if !declared.insert(*symbol) {
                    continue;
                }
                out.push_str(&format!("; use lib \"{}\"\n", cx.name_str(*lib)));
                out.push_str(&format!(
                    "declare {} @{}({})\n",
                    ll_ret(cx, func.ty)?,
                    c_ty::sanitize(cx.name_str(*symbol)),
                    ll_params(cx, func.ty)?
                ));
            }
        }
    }
    out.push('\n');

    let owns_global = |id: &crate::ir::ids::GlobalId| chunk_no == 0 && mine.globals.iter().any(|g| g == id);
    for module in modules {
        for id in &module.globals {
            let g = cx.global(*id);
            let name = c_expr::global_c_name(cx, g);
            let ty = ll_type(cx, g.ty)?;
            let align = llvm_ty::align(cx, g.ty);
            if owns_global(id) {
                let mut pre = String::new();
                let init = match &g.init {
                    Some(v) => ll_const_init(cx, g.ty, v, &name, &mut pre)?,
                    None => "zeroinitializer".to_string(),
                };
                out.push_str(&pre);
                out.push_str(&format!(
                    "@{name} = {}global {ty} {init}, align {align}\n",
                    tls(g),
                ));
            } else {
                out.push_str(&format!(
                    "@{name} = external {}global {ty}, align {align}\n",
                    tls(g),
                ));
            }
        }
    }
    if modules.iter().any(|m| !m.globals.is_empty()) {
        out.push('\n');
    }

    let mut dbg = if opts.cc.debug {
        DebugOut::prepare(cx, std::slice::from_ref(mine), Some(defined))
    } else {
        DebugOut::off()
    };
    if dbg.enabled() {
        out.push_str("declare void @llvm.dbg.declare(metadata, metadata, metadata)\n\n");
    }
    let owns_func = |id: &FuncId| defined.contains(id);
    for module in modules {
        for id in &module.funcs {
            let func = cx.func(*id);
            match &func.kind {
                FuncKind::J3 { .. } if !owns_func(id) => {
                    out.push_str(&format!(
                        "declare {} @{}({})\n",
                        ll_ret(cx, func.ty)?,
                        c_expr::func_c_name(cx, func),
                        ll_params(cx, func.ty)?
                    ));
                }
                FuncKind::J3 { body } => {
                    let slot = if dbg.enabled() {
                        Some(&mut dbg)
                    } else {
                        None
                    };
                    let mut f = LlvmFn::new(cx, body, slot);
                    f.external = true;
                    out.push_str(&f.emit_func(func)?);
                    out.push('\n');
                }
                FuncKind::Decl | FuncKind::Lib { .. } => {}
            }
        }
    }

    if index == entry_module(cx, modules)? && chunk_no == 0 {
        let entry = host_entry(cx, modules)?;
        let crash = opts.cc.debug && super::llvm_crash::supported(triple);
        if crash {
            out.push_str(&super::llvm_crash::definitions());
        }
        out.push_str("define i32 @main(i32 %argc, ptr %argv) {\n");
        if crash {
            out.push_str(&super::llvm_crash::install());
        }
        if let Some(set_args) = sys_func(cx, modules, "setArgs") {
            out.push_str("  %argc64 = sext i32 %argc to i64\n");
            out.push_str(&format!("  call void @{set_args}(i64 %argc64, ptr %argv)\n"));
        }
        out.push_str(&format!("  call void @{entry}()\n"));
        out.push_str("  ret i32 0\n");
        out.push_str("}\n");
    }
    let meta = dbg.finish();
    if !meta.is_empty() {
        out.push('\n');
        out.push_str(super::llvm_crash::ATTRS);
        out.push_str(&meta);
    }
    if out.contains(" frem ") {
        out.push_str("; use lib \"m\"\n");
    }
    Ok(out)
}

/// Rough cost of each function in `module.funcs`: length of its IR dump (0 for non-J3 kinds).
#[cfg(test)]
pub(crate) fn func_weights(cx: &IrCx, module: &Module) -> Vec<usize> {
    module
        .funcs
        .iter()
        .map(|id| {
            let func = cx.func(*id);
            match &func.kind {
                FuncKind::J3 { .. } => {
                    let mut s = String::new();
                    crate::ir::dump::dump_func(cx, func, &mut s);
                    s.len()
                }
                _ => 0,
            }
        })
        .collect()
}

/// Which of `n` chunks defines each function, given their weights: biggest first into the
/// lightest chunk.
pub(crate) fn chunk_assign(w: &[usize], n: usize) -> Vec<usize> {
    let mut order: Vec<usize> = (0..w.len()).collect();
    order.sort_by_key(|i| std::cmp::Reverse(w[*i]));
    let mut load = vec![0usize; n.max(1)];
    let mut part = vec![0usize; w.len()];
    for i in order {
        let c = (0..load.len()).min_by_key(|c| load[*c]).unwrap_or(0);
        load[c] += w[i].max(1);
        part[i] = c;
    }
    part
}

/// Module that should define host `@main`: `j3.sys.start` if present, else the last `main`.
fn entry_module(cx: &IrCx, modules: &[Module]) -> Result<usize, String> {
    let mut start = None;
    let mut main = None;
    for (i, module) in modules.iter().enumerate() {
        let is_sys = module.name.len() == 2
            && cx.name_str(module.name[0]) == "j3"
            && cx.name_str(module.name[1]) == "sys";
        for id in &module.funcs {
            let name = cx.name_str(cx.func(*id).name);
            if name == "start" && is_sys {
                start = Some(i);
            }
            if name == "main" {
                main = Some(i);
            }
        }
    }
    start
        .or(main)
        .ok_or_else(|| "LLVM emit needs j3.sys.start or fn main()".to_string())
}

fn ll_ret(cx: &IrCx, fn_ty: Ty) -> Result<String, String> {
    let (_, ret) = cx.fn_sig(fn_ty).ok_or("not a fn type")?;
    if ret == cx.common.void {
        Ok("void".to_string())
    } else {
        ll_type(cx, ret)
    }
}

fn ll_params(cx: &IrCx, fn_ty: Ty) -> Result<String, String> {
    let (params, _) = cx.fn_sig(fn_ty).ok_or("not a fn type")?;
    let mut s = String::new();
    for (i, p) in params.iter().enumerate() {
        if i > 0 {
            s.push_str(", ");
        }
        s.push_str(&ll_type(cx, *p)?);
    }
    Ok(s)
}

fn sys_func(cx: &IrCx, modules: &[Module], name: &str) -> Option<String> {
    for module in modules {
        let is_sys = module.name.len() == 2
            && cx.name_str(module.name[0]) == "j3"
            && cx.name_str(module.name[1]) == "sys";
        if !is_sys {
            continue;
        }
        for id in &module.funcs {
            let func = cx.func(*id);
            if cx.name_str(func.name) == name {
                return Some(c_expr::func_c_name(cx, func));
            }
        }
    }
    None
}

fn host_entry(cx: &IrCx, modules: &[Module]) -> Result<String, String> {
    let mut start = None;
    let mut main = None;
    for module in modules {
        let is_sys = module.name.len() == 2
            && cx.name_str(module.name[0]) == "j3"
            && cx.name_str(module.name[1]) == "sys";
        for id in &module.funcs {
            let func = cx.func(*id);
            let name = cx.name_str(func.name);
            if name == "start" && is_sys {
                start = Some(c_expr::func_c_name(cx, func));
            }
            if name == "main" {
                main = Some(c_expr::func_c_name(cx, func));
            }
        }
    }
    start
        .or(main)
        .ok_or_else(|| "LLVM emit needs j3.sys.start or fn main()".to_string())
}

fn emit_struct_types(cx: &IrCx, modules: &[Module], out: &mut String) -> Result<(), String> {
    let mut ids = Vec::new();
    for module in modules {
        for id in &module.structs {
            if !ids.contains(id) {
                ids.push(*id);
            }
        }
    }
    let mut ordered = Vec::new();
    let mut seen = HashSet::new();
    for id in ids {
        visit_struct(cx, id, &mut seen, &mut ordered);
    }
    for id in &ordered {
        let def = cx.struct_def(*id);
        let name = llvm_ty::struct_name(cx, *id);
        let packed = def.packed;
        let mut fields = Vec::new();
        for f in &def.fields {
            fields.push(ll_type(cx, f.ty)?);
        }
        let inner = fields.join(", ");
        if packed {
            out.push_str(&format!("%{name} = type <{{ {inner} }}>\n"));
        } else {
            out.push_str(&format!("%{name} = type {{ {inner} }}\n"));
        }
    }
    if !ordered.is_empty() {
        out.push('\n');
    }
    Ok(())
}

fn visit_struct(cx: &IrCx, id: StructId, seen: &mut HashSet<StructId>, ordered: &mut Vec<StructId>) {
    if !seen.insert(id) {
        return;
    }
    for field in &cx.struct_def(id).fields {
        if let TyKind::Struct(dep) = cx.ty_kind(field.ty) {
            visit_struct(cx, *dep, seen, ordered);
        }
        if let TyKind::Array { elem, .. } = cx.ty_kind(field.ty) {
            if let TyKind::Struct(dep) = cx.ty_kind(*elem) {
                visit_struct(cx, *dep, seen, ordered);
            }
        }
    }
    ordered.push(id);
}

fn emit_enum_types(cx: &IrCx, modules: &[Module], out: &mut String) -> Result<(), String> {
    let mut any = false;
    for module in modules {
        for id in &module.enums {
            let def = cx.enum_def(*id);
            if def.is_c_like() {
                continue;
            }
            any = true;
            let ty = cx
                .lookup_ty(&TyKind::Enum(*id))
                .ok_or_else(|| "enum type not interned".to_string())?;
            let sz = abi::size(cx, ty);
            let rest = if sz > 4 { sz - 4 } else { 0 };
            let name = llvm_ty::enum_name(cx, *id);
            out.push_str(&format!("%{name} = type {{ i32, [{rest} x i8] }}\n"));
        }
    }
    if any {
        out.push('\n');
    }
    Ok(())
}

fn ll_const_init(
    cx: &IrCx,
    ty: Ty,
    init: &ConstInit,
    gname: &str,
    pre: &mut String,
) -> Result<String, String> {
    match init {
        ConstInit::Scalar(Operand::Const(c)) if matches!(&c.kind, ConstKind::Bytes(_)) => {
            // A string in static data: its bytes get a private global emitted before this one.
            let ConstKind::Bytes(bytes) = &c.kind else { unreachable!() };
            let n = pre.matches('\n').count();
            pre.push_str(&format!(
                "@.cb.{gname}.{n} = private unnamed_addr constant [{} x i8] {}\n",
                bytes.len(),
                llvm_expr::ll_bytes_lit(bytes)
            ));
            Ok(format!("{{ ptr @.cb.{gname}.{n}, i64 {} }}", bytes.len()))
        }
        ConstInit::Scalar(op) => {
            let mut dummy = LlvmFn::const_only(cx);
            dummy.operand_const(op)
        }
        ConstInit::Fields(fs) => {
            let mut parts = Vec::new();
            match cx.ty_kind(ty) {
                TyKind::Struct(id) => {
                    let def = cx.struct_def(*id);
                    for f in &def.fields {
                        let fname = cx.name_str(f.name);
                        let child = fs
                            .iter()
                            .find(|(n, _)| n == fname)
                            .map(|(_, v)| v);
                        match child {
                            Some(v) => parts.push(format!(
                                "{} {}",
                                ll_type(cx, f.ty)?,
                                ll_const_init(cx, f.ty, v, gname, pre)?
                            )),
                            None => parts.push(format!("{} zeroinitializer", ll_type(cx, f.ty)?)),
                        }
                    }
                    Ok(format!("{{ {} }}", parts.join(", ")))
                }
                _ => Ok("zeroinitializer".to_string()),
            }
        }
        ConstInit::Elems(es) => {
            let (elem, _) = match cx.ty_kind(ty) {
                TyKind::Array { elem, .. } => (*elem, ()),
                _ => return Ok("zeroinitializer".to_string()),
            };
            let mut parts = Vec::new();
            for v in es {
                parts.push(format!(
                    "{} {}",
                    ll_type(cx, elem)?,
                    ll_const_init(cx, elem, v, gname, pre)?
                ));
            }
            Ok(format!("[ {} ]", parts.join(", ")))
        }
    }
}

/// `thread_local ` for a `#[thread]` global, else empty.
fn tls(g: &crate::ir::entity::GlobalDef) -> &'static str {
    if g.thread {
        "thread_local "
    } else {
        ""
    }
}

