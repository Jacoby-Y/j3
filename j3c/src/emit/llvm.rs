/// Which functions one LLVM text defines. A split build compiles the script VM at `-O2`
/// as its own object while the rest of a dev build stays at the project's `opt`.
#[derive(Clone, Copy)]
pub enum Part<'a> {
    Whole,
    /// Define only these; declare everything else, and reference globals as external.
    Only(&'a HashSet<FuncId>),
    /// Define everything except these, plus `main` and every global.
    Except(&'a HashSet<FuncId>),
}

impl Part<'_> {
    fn defines(&self, id: FuncId) -> bool {
        match self {
            Part::Whole => true,
            Part::Only(set) => set.contains(&id),
            Part::Except(set) => !set.contains(&id),
        }
    }

    fn split(&self) -> bool {
        !matches!(self, Part::Whole)
    }
}

pub fn emit_llvm(cx: &IrCx, modules: &[Module], opts: &EmitOpts) -> Result<String, String> {
    emit_llvm_part(cx, modules, opts, Part::Whole)
}

pub fn emit_llvm_part(
    cx: &IrCx,
    modules: &[Module],
    opts: &EmitOpts,
    part: Part,
) -> Result<String, String> {
    let triple = if opts.target.is_empty() {
        "x86_64-pc-linux-gnu"
    } else {
        opts.target.as_str()
    };
    let mut out = String::new();
    out.push_str("; generated by j3c — LLVM printer\n");
    out.push_str(&format!("target triple = \"{triple}\"\n"));
    out.push_str("target datalayout = \"e-m:e-p270:32:32-p271:32:32-p272:64:64-i64:64-i128:128-f80:128-n8:16:32:64-S128\"\n\n");
    out.push_str("%j3_string = type { ptr, i64 }\n\n");

    emit_struct_types(cx, modules, &mut out)?;
    emit_enum_types(cx, modules, &mut out)?;

    if crate::emit::contains_syscall(cx, modules) {
        out.push_str("declare i64 @syscall(i64, ...)\n");
    }
    out.push_str("declare void @_exit(i32) noreturn\n");
    out.push_str("declare i64 @write(i32, ptr, i64)\n");
    out.push_str("declare void @llvm.memcpy.p0.p0.i64(ptr noalias nocapture writeonly, ptr noalias nocapture readonly, i64, i1 immarg)\n");
    out.push_str("declare i32 @snprintf(ptr noundef, i64 noundef, ptr noundef, ...)\n");
    out.push_str("declare i32 @puts(ptr)\n\n");

    out.push_str("@.j3_fmt_i64 = private unnamed_addr constant [5 x i8] c\"%lld\\00\"\n");
    out.push_str("@.j3_fmt_f = private unnamed_addr constant [3 x i8] c\"%g\\00\"\n");
    out.push_str("@.j3_fmt_s = private unnamed_addr constant [3 x i8] c\"%s\\00\"\n");
    out.push_str("@.j3_true = private unnamed_addr constant [5 x i8] c\"true\\00\"\n");
    out.push_str("@.j3_false = private unnamed_addr constant [6 x i8] c\"false\\00\"\n\n");

    // Several modules may bind the same C function (`getenv` in two `use lib "c"` blocks);
    // LLVM takes one declaration per symbol.
    let mut declared = std::collections::HashSet::new();
    for module in modules {
        for id in &module.funcs {
            let func = cx.func(*id);
            if let FuncKind::Lib { lib, symbol } = &func.kind {
                if !declared.insert(*symbol) { continue; }
                out.push_str(&format!("; use lib \"{}\"\n", cx.name_str(*lib)));
                out.push_str(&format!(
                    "declare {} @{}({})\n",
                    ll_ret(cx, func.ty)?,
                    c_ty::sanitize(cx.name_str(*symbol)),
                    ll_params(cx, func.ty)?
                ));
            }
        }
    }
    out.push('\n');

    for module in modules {
        for id in &module.globals {
            let g = cx.global(*id);
            let name = c_expr::global_c_name(cx, g);
            let ty = ll_type(cx, g.ty)?;
            if matches!(part, Part::Only(_)) {
                out.push_str(&format!(
                    "@{name} = external global {ty}, align {}\n",
                    llvm_ty::align(cx, g.ty)
                ));
                continue;
            }
            let init = match &g.init {
                Some(v) => ll_const_init(cx, g.ty, v)?,
                None => "zeroinitializer".to_string(),
            };
            let linkage = if part.split() { "" } else { "internal " };
            out.push_str(&format!(
                "@{name} = {linkage}global {ty} {init}, align {}\n",
                llvm_ty::align(cx, g.ty)
            ));
        }
    }
    if modules.iter().any(|m| !m.globals.is_empty()) {
        out.push('\n');
    }

    let mut dbg = if opts.cc.debug && !matches!(part, Part::Only(_)) {
        DebugOut::prepare(cx, modules)
    } else {
        DebugOut::off()
    };
    if dbg.enabled() {
        out.push_str("declare void @llvm.dbg.declare(metadata, metadata, metadata)\n\n");
    }
    for module in modules {
        for id in &module.funcs {
            let func = cx.func(*id);
            match &func.kind {
                FuncKind::J3 { .. } if !part.defines(*id) => {
                    out.push_str(&format!(
                        "declare {} @{}({})\n",
                        ll_ret(cx, func.ty)?,
                        c_expr::func_c_name(cx, func),
                        ll_params(cx, func.ty)?
                    ));
                }
                FuncKind::J3 { body } => {
                    let slot = if dbg.enabled() {
                        Some(&mut dbg)
                    } else {
                        None
                    };
                    let mut f = LlvmFn::new(cx, body, slot);
                    f.external = part.split();
                    out.push_str(&f.emit_func(func)?);
                    out.push('\n');
                }
                FuncKind::Decl | FuncKind::Lib { .. } => {}
            }
        }
    }

    if !matches!(part, Part::Only(_)) {
        let entry = host_entry(cx, modules)?;
        let crash = opts.cc.debug && super::llvm_crash::supported(triple);
        if crash {
            out.push_str(&super::llvm_crash::definitions());
        }
        out.push_str("define i32 @main(i32 %argc, ptr %argv) {\n");
        if crash {
            out.push_str(&super::llvm_crash::install());
        }
        if let Some(set_args) = sys_func(cx, modules, "setArgs") {
            out.push_str("  %argc64 = sext i32 %argc to i64\n");
            out.push_str(&format!("  call void @{set_args}(i64 %argc64, ptr %argv)\n"));
        }
        out.push_str(&format!("  call void @{entry}()\n"));
        out.push_str("  ret i32 0\n");
        out.push_str("}\n");
    }
    let meta = dbg.finish();
    if !meta.is_empty() {
        out.push('\n');
        out.push_str(super::llvm_crash::ATTRS);
        out.push_str(&meta);
    }
    // `frem` lowers to a libm call.
    // ponytail: text scan for frem; flag it in the printer if this grows
    if out.contains(" frem ") {
        out.push_str("; use lib \"m\"\n");
    }
    Ok(out)
}

/// One module's LLVM text. Types are duplicated. This module's functions and
/// globals are defined (external linkage); everything else is declared. `@main`
/// is only in the module that owns `j3.sys.start` or user `main`.
pub(crate) fn emit_llvm_module(
    cx: &IrCx,
    modules: &[Module],
    index: usize,
    opts: &EmitOpts,
) -> Result<String, String> {
    let mine = &modules[index];
    let triple = if opts.target.is_empty() {
        "x86_64-pc-linux-gnu"
    } else {
        opts.target.as_str()
    };
    let mut out = String::new();
    out.push_str("; generated by j3c — LLVM printer\n");
    out.push_str(&format!("target triple = \"{triple}\"\n"));
    out.push_str("target datalayout = \"e-m:e-p270:32:32-p271:32:32-p272:64:64-i64:64-i128:128-f80:128-n8:16:32:64-S128\"\n\n");
    out.push_str("%j3_string = type { ptr, i64 }\n\n");

    emit_struct_types(cx, modules, &mut out)?;
    emit_enum_types(cx, modules, &mut out)?;

    if crate::emit::contains_syscall(cx, modules) {
        out.push_str("declare i64 @syscall(i64, ...)\n");
    }
    out.push_str("declare void @_exit(i32) noreturn\n");
    out.push_str("declare i64 @write(i32, ptr, i64)\n");
    out.push_str("declare void @llvm.memcpy.p0.p0.i64(ptr noalias nocapture writeonly, ptr noalias nocapture readonly, i64, i1 immarg)\n");
    out.push_str("declare i32 @snprintf(ptr noundef, i64 noundef, ptr noundef, ...)\n");
    out.push_str("declare i32 @puts(ptr)\n\n");

    out.push_str("@.j3_fmt_i64 = private unnamed_addr constant [5 x i8] c\"%lld\\00\"\n");
    out.push_str("@.j3_fmt_f = private unnamed_addr constant [3 x i8] c\"%g\\00\"\n");
    out.push_str("@.j3_fmt_s = private unnamed_addr constant [3 x i8] c\"%s\\00\"\n");
    out.push_str("@.j3_true = private unnamed_addr constant [5 x i8] c\"true\\00\"\n");
    out.push_str("@.j3_false = private unnamed_addr constant [6 x i8] c\"false\\00\"\n\n");

    let mut declared = HashSet::new();
    for module in modules {
        for id in &module.funcs {
            let func = cx.func(*id);
            if let FuncKind::Lib { lib, symbol } = &func.kind {
                if !declared.insert(*symbol) {
                    continue;
                }
                out.push_str(&format!("; use lib \"{}\"\n", cx.name_str(*lib)));
                out.push_str(&format!(
                    "declare {} @{}({})\n",
                    ll_ret(cx, func.ty)?,
                    c_ty::sanitize(cx.name_str(*symbol)),
                    ll_params(cx, func.ty)?
                ));
            }
        }
    }
    out.push('\n');

    let owns_global = |id: &crate::ir::ids::GlobalId| mine.globals.iter().any(|g| g == id);
    for module in modules {
        for id in &module.globals {
            let g = cx.global(*id);
            let name = c_expr::global_c_name(cx, g);
            let ty = ll_type(cx, g.ty)?;
            let align = llvm_ty::align(cx, g.ty);
            if owns_global(id) {
                let init = match &g.init {
                    Some(v) => ll_const_init(cx, g.ty, v)?,
                    None => "zeroinitializer".to_string(),
                };
                out.push_str(&format!("@{name} = global {ty} {init}, align {align}\n"));
            } else {
                out.push_str(&format!(
                    "@{name} = external global {ty}, align {align}\n"
                ));
            }
        }
    }
    if modules.iter().any(|m| !m.globals.is_empty()) {
        out.push('\n');
    }

    let mut dbg = if opts.cc.debug {
        DebugOut::prepare(cx, std::slice::from_ref(mine))
    } else {
        DebugOut::off()
    };
    if dbg.enabled() {
        out.push_str("declare void @llvm.dbg.declare(metadata, metadata, metadata)\n\n");
    }
    let owns_func = |id: &FuncId| mine.funcs.iter().any(|f| f == id);
    for module in modules {
        for id in &module.funcs {
            let func = cx.func(*id);
            match &func.kind {
                FuncKind::J3 { .. } if !owns_func(id) => {
                    out.push_str(&format!(
                        "declare {} @{}({})\n",
                        ll_ret(cx, func.ty)?,
                        c_expr::func_c_name(cx, func),
                        ll_params(cx, func.ty)?
                    ));
                }
                FuncKind::J3 { body } => {
                    let slot = if dbg.enabled() {
                        Some(&mut dbg)
                    } else {
                        None
                    };
                    let mut f = LlvmFn::new(cx, body, slot);
                    f.external = true;
                    out.push_str(&f.emit_func(func)?);
                    out.push('\n');
                }
                FuncKind::Decl | FuncKind::Lib { .. } => {}
            }
        }
    }

    if index == entry_module(cx, modules)? {
        let entry = host_entry(cx, modules)?;
        let crash = opts.cc.debug && super::llvm_crash::supported(triple);
        if crash {
            out.push_str(&super::llvm_crash::definitions());
        }
        out.push_str("define i32 @main(i32 %argc, ptr %argv) {\n");
        if crash {
            out.push_str(&super::llvm_crash::install());
        }
        if let Some(set_args) = sys_func(cx, modules, "setArgs") {
            out.push_str("  %argc64 = sext i32 %argc to i64\n");
            out.push_str(&format!("  call void @{set_args}(i64 %argc64, ptr %argv)\n"));
        }
        out.push_str(&format!("  call void @{entry}()\n"));
        out.push_str("  ret i32 0\n");
        out.push_str("}\n");
    }
    let meta = dbg.finish();
    if !meta.is_empty() {
        out.push('\n');
        out.push_str(super::llvm_crash::ATTRS);
        out.push_str(&meta);
    }
    if out.contains(" frem ") {
        out.push_str("; use lib \"m\"\n");
    }
    Ok(out)
}

/// Module that should define host `@main`: `j3.sys.start` if present, else the last `main`.
fn entry_module(cx: &IrCx, modules: &[Module]) -> Result<usize, String> {
    let mut start = None;
    let mut main = None;
    for (i, module) in modules.iter().enumerate() {
        let is_sys = module.name.len() == 2
            && cx.name_str(module.name[0]) == "j3"
            && cx.name_str(module.name[1]) == "sys";
        for id in &module.funcs {
            let name = cx.name_str(cx.func(*id).name);
            if name == "start" && is_sys {
                start = Some(i);
            }
            if name == "main" {
                main = Some(i);
            }
        }
    }
    start
        .or(main)
        .ok_or_else(|| "LLVM emit needs j3.sys.start or fn main()".to_string())
}

fn ll_ret(cx: &IrCx, fn_ty: Ty) -> Result<String, String> {
    let (_, ret) = cx.fn_sig(fn_ty).ok_or("not a fn type")?;
    if ret == cx.common.void {
        Ok("void".to_string())
    } else {
        ll_type(cx, ret)
    }
}

fn ll_params(cx: &IrCx, fn_ty: Ty) -> Result<String, String> {
    let (params, _) = cx.fn_sig(fn_ty).ok_or("not a fn type")?;
    let mut s = String::new();
    for (i, p) in params.iter().enumerate() {
        if i > 0 {
            s.push_str(", ");
        }
        s.push_str(&ll_type(cx, *p)?);
    }
    Ok(s)
}

fn sys_func(cx: &IrCx, modules: &[Module], name: &str) -> Option<String> {
    for module in modules {
        let is_sys = module.name.len() == 2
            && cx.name_str(module.name[0]) == "j3"
            && cx.name_str(module.name[1]) == "sys";
        if !is_sys {
            continue;
        }
        for id in &module.funcs {
            let func = cx.func(*id);
            if cx.name_str(func.name) == name {
                return Some(c_expr::func_c_name(cx, func));
            }
        }
    }
    None
}

fn host_entry(cx: &IrCx, modules: &[Module]) -> Result<String, String> {
    let mut start = None;
    let mut main = None;
    for module in modules {
        let is_sys = module.name.len() == 2
            && cx.name_str(module.name[0]) == "j3"
            && cx.name_str(module.name[1]) == "sys";
        for id in &module.funcs {
            let func = cx.func(*id);
            let name = cx.name_str(func.name);
            if name == "start" && is_sys {
                start = Some(c_expr::func_c_name(cx, func));
            }
            if name == "main" {
                main = Some(c_expr::func_c_name(cx, func));
            }
        }
    }
    start
        .or(main)
        .ok_or_else(|| "LLVM emit needs j3.sys.start or fn main()".to_string())
}

fn emit_struct_types(cx: &IrCx, modules: &[Module], out: &mut String) -> Result<(), String> {
    let mut ids = Vec::new();
    for module in modules {
        for id in &module.structs {
            if !ids.contains(id) {
                ids.push(*id);
            }
        }
    }
    let mut ordered = Vec::new();
    let mut seen = HashSet::new();
    for id in ids {
        visit_struct(cx, id, &mut seen, &mut ordered);
    }
    for id in &ordered {
        let def = cx.struct_def(*id);
        let name = llvm_ty::struct_name(cx, *id);
        let packed = def.packed;
        let mut fields = Vec::new();
        for f in &def.fields {
            fields.push(ll_type(cx, f.ty)?);
        }
        let inner = fields.join(", ");
        if packed {
            out.push_str(&format!("%{name} = type <{{ {inner} }}>\n"));
        } else {
            out.push_str(&format!("%{name} = type {{ {inner} }}\n"));
        }
    }
    if !ordered.is_empty() {
        out.push('\n');
    }
    Ok(())
}

fn visit_struct(cx: &IrCx, id: StructId, seen: &mut HashSet<StructId>, ordered: &mut Vec<StructId>) {
    if !seen.insert(id) {
        return;
    }
    for field in &cx.struct_def(id).fields {
        if let TyKind::Struct(dep) = cx.ty_kind(field.ty) {
            visit_struct(cx, *dep, seen, ordered);
        }
        if let TyKind::Array { elem, .. } = cx.ty_kind(field.ty) {
            if let TyKind::Struct(dep) = cx.ty_kind(*elem) {
                visit_struct(cx, *dep, seen, ordered);
            }
        }
    }
    ordered.push(id);
}

fn emit_enum_types(cx: &IrCx, modules: &[Module], out: &mut String) -> Result<(), String> {
    let mut any = false;
    for module in modules {
        for id in &module.enums {
            let def = cx.enum_def(*id);
            if def.is_c_like() {
                continue;
            }
            any = true;
            let ty = cx
                .lookup_ty(&TyKind::Enum(*id))
                .ok_or_else(|| "enum type not interned".to_string())?;
            let sz = abi::size(cx, ty);
            let rest = if sz > 4 { sz - 4 } else { 0 };
            let name = llvm_ty::enum_name(cx, *id);
            out.push_str(&format!("%{name} = type {{ i32, [{rest} x i8] }}\n"));
        }
    }
    if any {
        out.push('\n');
    }
    Ok(())
}

fn ll_const_init(cx: &IrCx, ty: Ty, init: &ConstInit) -> Result<String, String> {
    match init {
        ConstInit::Scalar(op) => {
            let mut dummy = LlvmFn::const_only(cx);
            dummy.operand_const(op)
        }
        ConstInit::Fields(fs) => {
            let mut parts = Vec::new();
            match cx.ty_kind(ty) {
                TyKind::Struct(id) => {
                    let def = cx.struct_def(*id);
                    for f in &def.fields {
                        let fname = cx.name_str(f.name);
                        let child = fs
                            .iter()
                            .find(|(n, _)| n == fname)
                            .map(|(_, v)| v);
                        match child {
                            Some(v) => parts.push(format!(
                                "{} {}",
                                ll_type(cx, f.ty)?,
                                ll_const_init(cx, f.ty, v)?
                            )),
                            None => parts.push(format!("{} zeroinitializer", ll_type(cx, f.ty)?)),
                        }
                    }
                    Ok(format!("{{ {} }}", parts.join(", ")))
                }
                _ => Ok("zeroinitializer".to_string()),
            }
        }
        ConstInit::Elems(es) => {
            let (elem, _) = match cx.ty_kind(ty) {
                TyKind::Array { elem, .. } => (*elem, ()),
                _ => return Ok("zeroinitializer".to_string()),
            };
            let mut parts = Vec::new();
            for v in es {
                parts.push(format!(
                    "{} {}",
                    ll_type(cx, elem)?,
                    ll_const_init(cx, elem, v)?
                ));
            }
            Ok(format!("[ {} ]", parts.join(", ")))
        }
    }
}
