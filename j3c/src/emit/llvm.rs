//! LLVM IR printer. Same typed IR as C; clang/llc compile the text.
//! No libLLVM, no crates.io.

use std::collections::HashSet;

use crate::emit::c_expr;
use crate::emit::c_ty;
use crate::emit::llvm_expr::{DebugOut, LlvmFn};
use crate::emit::llvm_ty::{self, ll_type};
use crate::emit::opts::EmitOpts;
use crate::ir::abi;
use crate::ir::cx::IrCx;
use crate::ir::entity::{ConstInit, FuncKind};
use crate::ir::ids::{FuncId, StructId};
