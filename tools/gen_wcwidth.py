#!/usr/bin/env python3
"""Generate j3c/stdlib/j3/term/width.j3, the terminal column width of a code point.

Uses only Python's built-in unicodedata (no download). Run: python3 tools/gen_wcwidth.py [OUT]
The output is checked in; rerun this script after a Python upgrade, do not edit the tables by hand.
"""

import os
import sys
import unicodedata

MAX_CP = 0x10FFFF
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(REPO, "j3c", "stdlib", "j3", "term", "width.j3")

SOFT_HYPHEN = 0xAD  # Cf, but printed as one column
ZERO_EXTRA = [(0x200B, 0x200B), (0x1160, 0x11FF), (0xFE00, 0xFE0F)]  # Hangul medial/final jamo are Lo
WIDE_EXTRA = [(0x1F300, 0x1F64F), (0x1F900, 0x1F9FF)]  # emoji blocks, some not marked W in Unicode
LINE_LIMIT = 104  # longest table line, without the 4-space indent


def runs(pred):
    """Maximal inclusive (lo, hi) runs of the code points where pred holds."""
    out = []
    start = None
    for cp in range(MAX_CP + 1):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX_CP))
    return out


def merge(ranges):
    """Sort, then join ranges that overlap or touch."""
    out = []
    for lo, hi in sorted(ranges):
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], hi))
        else:
            out.append((lo, hi))
    return out


def subtract(ranges, cut):
    """The code points of `ranges` not in `cut`; both sorted and merged."""
    out = []
    for lo, hi in ranges:
        for clo, chi in cut:
            if chi < lo or clo > hi:
                continue
            if clo > lo:
                out.append((lo, clo - 1))
            lo = max(lo, chi + 1)
            if lo > hi:
                break
        if lo <= hi:
            out.append((lo, hi))
    return merge(out)


def table(name, ranges):
    flat = [f"0x{v:04x}" for r in ranges for v in r]
    lines = []
    cur = ""
    for i in range(0, len(flat), 2):
        pair = f"{flat[i]}, {flat[i + 1]}, "
        if cur and len(cur) + len(pair) > LINE_LIMIT:
            lines.append(cur.rstrip())
            cur = ""
        cur += pair
    if cur:
        lines.append(cur.rstrip())
    body = "\n".join("    " + line for line in lines)
    return f"const {name}: [{len(flat)}]i32 = [\n{body}\n];\n"


def build():
    def zero_pred(cp):
        if cp == SOFT_HYPHEN:
            return False
        return unicodedata.category(chr(cp)) in ("Mn", "Me", "Cf")

    def wide_pred(cp):
        return unicodedata.east_asian_width(chr(cp)) in ("W", "F")

    zero = merge(runs(zero_pred) + ZERO_EXTRA)
    # A few combining marks (U+302A..U+302D, U+3099..U+309A) are W; zero wins, so the tables stay disjoint.
    wide = subtract(merge(runs(wide_pred) + WIDE_EXTRA), zero)
    return zero, wide


HEAD = """\
// Generated by tools/gen_wcwidth.py from Python's unicodedata (Unicode {version}). Do not edit by hand:
// rerun the script. Each table is inclusive (lo, hi) code point pairs, sorted, adjacent ranges merged.
// The two tables are disjoint; ZERO is checked first.

/// Terminal column width of a code point: 0 (combining, format, controls), 1, or 2 (East Asian wide,
/// emoji). Per code point, not per grapheme: a ZWJ sequence is the sum of its parts. Any thread, no state.
module j3.term.width;

/// Returns 0 for a control (C0, DEL, C1), 0 for a zero-width code point, 2 for a wide one, else 1.
pub fn cpWidth(cp: i32): int {{
    if cp < 32 || (cp >= 0x7f && cp <= 0x9f) {{
        return 0;
    }}
    if cp < 0x7f {{
        return 1;
    }}
    if inTable(ZERO, cp) {{
        return 0;
    }}
    if inTable(WIDE, cp) {{
        return 2;
    }}
    return 1;
}}

/// Binary search over (lo, hi) pairs; `t.len / 2` pairs, sorted and disjoint.
fn inTable(t: []i32, cp: i32): bool {{
    let lo = 0;
    let hi = t.len / 2;
    while lo < hi {{
        let mid = (lo + hi) / 2;
        if t[2 * mid + 1] < cp {{
            lo = mid + 1;
        }} else if t[2 * mid] > cp {{
            hi = mid;
        }} else {{
            return true;
        }}
    }}
    return false;
}}

"""


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT
    zero, wide = build()
    text = HEAD.format(version=unicodedata.unidata_version)
    text += table("ZERO", zero) + "\n" + table("WIDE", wide)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {out}: {len(zero)} zero ranges, {len(wide)} wide ranges")


if __name__ == "__main__":
    main()
